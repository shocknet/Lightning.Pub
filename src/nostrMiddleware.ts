import Main from "./services/main/index.js"
import Nostr from "./services/nostr/index.js"
import { NostrEvent, NostrSend, NostrSettings } from "./services/nostr/nostrPool.js"
import * as Types from '../proto/autogenerated/ts/types.js'
import NewNostrTransport, { NostrRequest } from '../proto/autogenerated/ts/nostr_transport.js';
import { ERROR, getLogger } from "./services/helpers/logger.js";
import { isSupportedClinkEvent } from "./services/nostr/clinkVersion.js";
import { CLINK_SUPPORTED_KINDS } from "./services/CLINK/clinkConstants.js";
import { ClinkError, encodeClinkResponse } from "./services/CLINK/clinkTypes.js";
import { ClinkRouter } from "./services/serverMethods/clinkRouter.js";
import { newClinkTransport } from "./services/serverMethods/clinkTransport.js";

type ExportedCalls = { Stop: () => void, Send: NostrSend, Ping: () => Promise<void>, Reset: (settings: NostrSettings) => void }
type ClientEventCallback = (e: { requestId: string }, fromPub: string) => void
export default (
    serverMethods: Types.ServerMethods,
    clinkHandler: ClinkRouter,
    mainHandler: Main,
    nostrSettings: NostrSettings,
    onClientEvent: ClientEventCallback,
): ExportedCalls => {
    const log = getLogger({})
    const nostrTransport = NewNostrTransport(serverMethods, {
        NostrUserAuthGuard: async (appId, pub) => {
            const app = await mainHandler.storage.applicationStorage.GetApplication(appId || "")
            const nostrUser = await mainHandler.storage.applicationStorage.GetOrCreateNostrAppUser(app, pub || "")
            await mainHandler.storage.userStorage.UpsertUserAccess(nostrUser.user.user_id, Math.floor(Date.now() / 1000))
            mainHandler.backupManager.notifyBackupTable('application_users', 'user_balances')
            return { user_id: nostrUser.user.user_id, app_user_id: nostrUser.identifier, app_id: appId || "" }
        },
        NostrAdminAuthGuard: async (appId, pub) => {
            const adminNpub = mainHandler.adminManager.GetAdminNpub()
            if (!adminNpub) { throw new Error("admin access not configured") }
            if (pub !== adminNpub) { throw new Error("admin access denied") }
            log("admin access from", pub)
            return { admin_id: pub }
        },
        NostrMetricsAuthGuard: async (appId, pub) => {
            const adminNpub = mainHandler.adminManager.GetAdminNpub()
            if (!adminNpub) { throw new Error("admin access not configured") }
            if (pub !== adminNpub) { throw new Error("Metrics unavailable") }
            log("operator access from", pub)
            return { operator_id: pub, app_id: appId || "" }
        },
        metricsCallback: metrics => mainHandler.settings.getSettings().serviceSettings.recordPerformance ? mainHandler.metricsManager.AddMetrics(metrics) : null,
        NostrGuestWithPubAuthGuard: async (appId, pub) => {
            if (!pub || !appId) {
                throw new Error("Unknown error occured")
            }
            return { pub, app_id: appId }
        },
        logger: { log: console.log, error: err => log(ERROR, err) },
    })
    const clinkTransport = newClinkTransport(clinkHandler)

    const nostr = new Nostr(nostrSettings, mainHandler.utils, event => {
        if (CLINK_SUPPORTED_KINDS.includes(event.kind)) {
            if (event.relayConstraint === 'provider') {
                log("got clink request on provider only relay, ignoring")
                return
            }
            if (!isSupportedClinkEvent(event.tags)) {
                log("dropping unsupported clink_version", event.kind, event.id)
                const err = new ClinkError("Invalid Request: unsupported clink_version", 6)
                nostr.Send({ type: 'app', appId: event.appId }, { type: 'event', event: encodeClinkResponse(event.kind, err.getPayload(), event), encrypt: { toPub: event.pub } })
                return
            }
            void clinkTransport(event, reply => {
                nostr.Send({ type: 'app', appId: event.appId }, { type: 'event', event: reply, encrypt: { toPub: event.pub } })
                log("sent clink response", event.kind, event.id, event.pub)
            }).catch(err => log(ERROR, "clink request failed", err.message || err))
            return
        }

        let j: NostrRequest
        try {
            j = JSON.parse(event.content)
        } catch {
            log(ERROR, "invalid json event received", event.content)
            return
        }
        if (!j.rpcName) {
            if (event.relayConstraint === 'service') {
                log("got relay response on service only relay, ignoring")
            }
            onClientEvent(j as { requestId: string }, event.pub)
            return
        }
        if (event.relayConstraint === 'provider') {
            log("got service request on provider only relay, ignoring")
            return
        }
        if (j.authIdentifier !== event.pub) {
            log(ERROR, "authIdentifier does not match", j.authIdentifier || "--", event.pub)
            return
        }
        nostrTransport({ ...j, appId: event.appId }, res => {
            nostr.Send({ type: 'app', appId: event.appId },
                { type: 'content', pub: event.pub, content: JSON.stringify({ ...res, requestId: j.requestId }) })


        }, event.startAtNano, event.startAtMs)
    }, beacon => mainHandler.liquidityProvider.onBeaconEvent(beacon))

    // Mark nostr connected/ready after initial subscription tick
    mainHandler.adminManager.setNostrConnected(true)

    return {
        Stop: () => {
            mainHandler.adminManager.setNostrConnected(false)
            nostr.Stop()
        },
        Send: (...args) => nostr.Send(...args),
        Ping: () => nostr.Ping(),
        Reset: (settings: NostrSettings) => nostr.Reset(settings)
    }
}

import { AdminManager } from "../services/main/adminManager.js"
import { LiquidityProvider } from "../services/main/liquidityProvider.js"
import { Swaps } from "../services/lnd/swaps/swaps.js"
import SettingsManager from "../services/main/settingsManager.js"
import { Utils } from "../services/helpers/utilsWrapper.js"
import { NostrSender } from "../services/nostr/sender.js"
import * as Types from "../../proto/autogenerated/ts/types.js"
import { StorageTestBase } from "./testBase.js"

export const ignore = false
export const dev = false
export const requires = "storage" as const

const emptyReq = (): Types.AssetsAndLiabilitiesReqV2 => ({
    lnd_providers: [],
    liquidity_providers: [],
})

const peerPub = (n: number) => n.toString(16).padStart(64, "c")

type Harness = {
    T: StorageTestBase
    admin: AdminManager
    utils: Utils
    lp: LiquidityProvider
    pub: string
}

const setupHarness = async (T: StorageTestBase): Promise<Harness> => {
    const settings = new SettingsManager(T.storage)
    await settings.InitSettings()
    const pub = peerPub(Date.now())
    settings.OverrideTestSettings(s => {
        s.liquiditySettings.disableLiquidityProvider = true
        s.liquiditySettings.liquidityProviderPub = pub
        s.swapsSettings.boltzHttpUrl = ""
        s.swapsSettings.boltzWebSocketUrl = ""
        s.swapsSettings.boltsHttpUrlAlt = ""
        s.swapsSettings.boltsWebSocketUrlAlt = ""
        return s
    })
    const swaps = new Swaps(settings, T.storage)
    const admin = new AdminManager(settings, T.storage, swaps)
    const utils = new Utils({
        dataDir: T.storage.getStorageSettings().dataDir,
        allowResetMetricsStorages: true,
        noCollector: true,
    }, new NostrSender())
    const lp = new LiquidityProvider(
        () => settings.getSettings().liquiditySettings,
        utils,
        async () => { },
        async () => { },
    )
    admin.attachLiquidityProvider(lp)
    await T.storage.liquidityStorage.CreateTrackedProvider("lnPub", pub)
    return { T, admin, utils, lp, pub }
}

const teardownHarness = (h: Harness) => {
    h.admin.Stop()
    h.utils.Stop()
}

const testDisabledPeerDoesNotFailAssetsPage = async (h: Harness) => {
    h.T.d("starting testDisabledPeerDoesNotFailAssetsPage")
    const res = await h.admin.GetAssetsAndLiabilitiesV2(emptyReq())
    h.T.expect(Types.AssetsAndLiabilitiesV2Validate(res)).to.equal(null)
    const lp = res.liquidity_providers.find(p => p.pubkey === h.pub)
    h.T.expect(lp).to.not.equal(undefined)
    h.T.expect(lp!.tracked).to.equal(undefined)
    h.T.expect(res.lnds).to.deep.equal([])
    h.T.d("disabled liquidity provider returns untracked instead of throwing")
}

const testUnreachablePeerDoesNotFailAssets = async (h: Harness) => {
    h.T.d("starting testUnreachablePeerDoesNotFailAssets")
    h.lp.IsReady = () => true
    h.lp.GetOperations = async () => {
        throw new Error("liquidity provider is not ready yet, disabled or unreachable")
    }
    const provider = await h.T.storage.liquidityStorage.GetTrackedProvider("lnPub", h.pub)
    if (!provider) {
        throw new Error("expected tracked lnPub provider")
    }
    const res = await h.admin.GetProviderAssetsAndLiabilities(emptyReq(), provider)
    h.T.expect(res.pubkey).to.equal(h.pub)
    h.T.expect(res.tracked).to.equal(undefined)
    h.T.d("unreachable liquidity provider returns untracked instead of throwing")
}

export default async (T: StorageTestBase) => {
    const h = await setupHarness(T)
    try {
        await testDisabledPeerDoesNotFailAssetsPage(h)
        await testUnreachablePeerDoesNotFailAssets(h)
    } finally {
        teardownHarness(h)
    }
}

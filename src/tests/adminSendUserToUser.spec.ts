import * as Types from "../../proto/autogenerated/ts/types.js"
import { defaultInvoiceExpiry } from "../services/storage/paymentStorage.js"
import {
    expectThrowsAsync,
    runSanityCheck,
    safelySetUserBalance,
    TestBase,
    TestUserData,
    waitForUserBalance,
} from "./testBase.js"

export const ignore = false
export const dev = false

const FUNDING_SATS = 2000
const TRANSFER_SATS = 1000
const MANAGED_FEE_SATS = 6 // 60 bps of 1000 in test env
const ROOT_FEE_SATS = 6 // same 60 bps rootToUserFee in test env

export default async (T: TestBase) => {
    await safelySetUserBalance(T, T.user1, FUNDING_SATS)
    await testAdminSendUserToUserSuccess(T)
    await testAdminSendUserToUserOwnerSweep(T)
    await testAdminSendUserToUserInsufficientBalance(T)
    await testAdminSendUserToUserSameUser(T)
    await testAdminSendUserToUserBanned(T)
    await runSanityCheck(T)
}

const adminSend = (T: TestBase, req: Types.AdminSendUserToUserRequest) =>
    T.main.appUserManager.AdminSendUserToUser(req)

const testAdminSendUserToUserSuccess = async (T: TestBase) => {
    T.d("starting testAdminSendUserToUserSuccess")
    const application = await T.main.storage.applicationStorage.GetApplication(T.app.appId)
    const ownerBefore = await T.main.storage.userStorage.GetUser(application.owner.user_id)

    const res = await adminSend(T, {
        from_user_id: T.user1.userId,
        to_user_id: T.user2.userId,
        amount: TRANSFER_SATS,
    })
    T.expect(Types.AdminSendUserToUserResponseValidate(res)).to.equal(null)
    T.expect(res.amount).to.equal(TRANSFER_SATS)
    T.expect(res.fees).to.equal(MANAGED_FEE_SATS)

    const u1 = await T.main.storage.userStorage.GetUser(T.user1.userId)
    const u2 = await T.main.storage.userStorage.GetUser(T.user2.userId)
    const owner = await T.main.storage.userStorage.GetUser(application.owner.user_id)
    T.expect(u2.balance_sats).to.equal(TRANSFER_SATS)
    T.expect(u1.balance_sats).to.equal(FUNDING_SATS - TRANSFER_SATS - MANAGED_FEE_SATS)
    T.expect(owner.balance_sats).to.equal(ownerBefore.balance_sats + MANAGED_FEE_SATS)
    T.d("AdminSendUserToUser moved sats and credited app-owner fee")
}

const testAdminSendUserToUserOwnerSweep = async (T: TestBase) => {
    T.d("starting testAdminSendUserToUserOwnerSweep")
    const application = await T.main.storage.applicationStorage.GetApplication(T.app.appId)
    const ownerUser: TestUserData = {
        userId: application.owner.user_id,
        appUserIdentifier: "app-owner",
        appId: T.app.appId,
    }
    const ownerBefore = await T.main.storage.userStorage.GetUser(ownerUser.userId)
    const needed = FUNDING_SATS - ownerBefore.balance_sats
    if (needed > 0) {
        const invoice = await T.main.paymentManager.NewInvoice(
            ownerUser.userId,
            { amountSats: needed, memo: "fund owner for sweep" },
            { linkedApplication: application, expiry: defaultInvoiceExpiry },
        )
        await T.externalAccessToOtherLnd.PayInvoice(
            invoice.invoice, 0, { routingFeeLimit: 100, serviceFee: 100 }, needed,
            { from: "system", useProvider: false },
        )
        await waitForUserBalance(T, ownerUser.userId, FUNDING_SATS)
    }
    const u2Before = await T.main.storage.userStorage.GetUser(T.user2.userId)
    const ownerFunded = await T.main.storage.userStorage.GetUser(ownerUser.userId)

    const res = await adminSend(T, {
        from_user_id: ownerUser.userId,
        to_user_id: T.user2.userId,
        amount: TRANSFER_SATS,
    })
    T.expect(res.amount).to.equal(TRANSFER_SATS)
    T.expect(res.fees).to.equal(ROOT_FEE_SATS)

    const ownerAfter = await T.main.storage.userStorage.GetUser(ownerUser.userId)
    const u2After = await T.main.storage.userStorage.GetUser(T.user2.userId)
    T.expect(ownerAfter.balance_sats).to.equal(ownerFunded.balance_sats - TRANSFER_SATS - ROOT_FEE_SATS)
    T.expect(u2After.balance_sats).to.equal(u2Before.balance_sats + TRANSFER_SATS)
    T.d("owner sweep uses rootToUserFee and does not credit fee back to owner")
}

const testAdminSendUserToUserInsufficientBalance = async (T: TestBase) => {
    T.d("starting testAdminSendUserToUserInsufficientBalance")
    await expectThrowsAsync(
        adminSend(T, {
            from_user_id: T.user1.userId,
            to_user_id: T.user2.userId,
            amount: TRANSFER_SATS,
        }),
        "not enough balance to send payment",
    )
    T.d("insufficient balance rejected as expected")
}

const testAdminSendUserToUserSameUser = async (T: TestBase) => {
    T.d("starting testAdminSendUserToUserSameUser")
    await expectThrowsAsync(
        adminSend(T, {
            from_user_id: T.user1.userId,
            to_user_id: T.user1.userId,
            amount: 1,
        }),
        "from_user_id and to_user_id must be different",
    )
    T.d("same-user transfer rejected as expected")
}

const testAdminSendUserToUserBanned = async (T: TestBase) => {
    T.d("starting testAdminSendUserToUserBanned")
    await T.main.appUserManager.BanUser(T.user1.userId)
    await expectThrowsAsync(
        adminSend(T, {
            from_user_id: T.user1.userId,
            to_user_id: T.user2.userId,
            amount: 1,
        }),
        "one of the users is banned, cannot send payment",
    )
    T.d("banned sender rejected as expected")
}

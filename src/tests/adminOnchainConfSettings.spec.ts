import SettingsManager from "../services/main/settingsManager.js"
import { AdminManager } from "../services/main/adminManager.js"
import { Swaps } from "../services/lnd/swaps/swaps.js"
import {
    ADMIN_TIER1_CONFS_ENV,
    ADMIN_TIER1_LIMIT_ENV,
    isValidOnchainConfSettings,
} from "../services/main/adminNodeSettings.js"
import * as Types from "../../proto/autogenerated/ts/types.js"
import { expectThrowsAsync, StorageTestBase } from "./testBase.js"

export const ignore = false
export const dev = false
export const requires = "storage" as const

type Harness = {
    T: StorageTestBase
    settings: SettingsManager
}

type AdminHarness = Harness & {
    admin: AdminManager
}

const setupHarness = async (T: StorageTestBase): Promise<Harness> => {
    const settings = new SettingsManager(T.storage)
    await settings.InitSettings()
    return { T, settings }
}

const setupAdminHarness = async (T: StorageTestBase): Promise<AdminHarness> => {
    const { settings } = await setupHarness(T)
    settings.OverrideTestSettings(s => {
        s.swapsSettings.boltzHttpUrl = ""
        s.swapsSettings.boltzWebSocketUrl = ""
        s.swapsSettings.boltsHttpUrlAlt = ""
        s.swapsSettings.boltsWebSocketUrlAlt = ""
        return s
    })
    const admin = new AdminManager(settings, T.storage, new Swaps(settings, T.storage))
    return { T, settings, admin }
}

const confReq = (partial: Partial<Types.UpdateAdminOnchainConfSettingsRequest> = {}): Types.UpdateAdminOnchainConfSettingsRequest => ({
    tier1_limit_sats: 1_000_000,
    tier1_confs: 1,
    tier2_limit_sats: 100_000_000,
    tier2_confs: 2,
    tier3_confs: 3,
    ...partial,
})

const testValidationHelpers = (T: StorageTestBase) => {
    T.d("starting testValidationHelpers")
    T.expect(isValidOnchainConfSettings({
        tier1LimitSats: 1_000_000,
        tier1Confs: 1,
        tier2LimitSats: 100_000_000,
        tier2Confs: 2,
        tier3Confs: 3,
    })).to.equal(true)
    T.expect(isValidOnchainConfSettings({
        tier1LimitSats: 2_000_000,
        tier1Confs: 1,
        tier2LimitSats: 1_000_000,
        tier2Confs: 2,
        tier3Confs: 3,
    })).to.equal(false)
    T.expect(isValidOnchainConfSettings({
        tier1LimitSats: 1_000_000,
        tier1Confs: 3,
        tier2LimitSats: 100_000_000,
        tier2Confs: 2,
        tier3Confs: 3,
    })).to.equal(false)
    T.expect(isValidOnchainConfSettings({
        tier1LimitSats: 1_000_000,
        tier1Confs: 0,
        tier2LimitSats: 100_000_000,
        tier2Confs: 2,
        tier3Confs: 3,
    })).to.equal(false)
    T.d("helpers reject inverted limits and decreasing confs")
}

const testGetDefaults = async (h: AdminHarness) => {
    h.T.d("starting testGetDefaults")
    const shown = await h.admin.GetAdminOnchainConfSettings()
    h.T.expect(shown.tier1_limit_sats).to.equal(1_000_000)
    h.T.expect(shown.tier1_confs).to.equal(1)
    h.T.expect(shown.tier2_limit_sats).to.equal(100_000_000)
    h.T.expect(shown.tier2_confs).to.equal(2)
    h.T.expect(shown.tier3_confs).to.equal(3)
    h.T.expect(shown.tier1_limit_env_locked).to.equal(false)
    h.T.expect(shown.tier1_confs_env_locked).to.equal(false)
    h.T.expect(shown.tier2_limit_env_locked).to.equal(false)
    h.T.expect(shown.tier2_confs_env_locked).to.equal(false)
    h.T.expect(shown.tier3_confs_env_locked).to.equal(false)
    h.T.d("get returns default onchain conf tiers")
}

const testUpdatePersists = async (h: AdminHarness) => {
    h.T.d("starting testUpdatePersists")
    const shown = await h.admin.UpdateAdminOnchainConfSettings(confReq({
        tier1_limit_sats: 500_000,
        tier1_confs: 2,
        tier2_limit_sats: 50_000_000,
        tier2_confs: 3,
        tier3_confs: 6,
    }))
    h.T.expect(shown.tier1_limit_sats).to.equal(500_000)
    h.T.expect(shown.tier1_confs).to.equal(2)
    h.T.expect(shown.tier2_limit_sats).to.equal(50_000_000)
    h.T.expect(shown.tier2_confs).to.equal(3)
    h.T.expect(shown.tier3_confs).to.equal(6)

    const lnd = h.settings.getSettings().lndSettings
    h.T.expect(lnd.tier1LimitSats).to.equal(500_000)
    h.T.expect(lnd.tier1Confs).to.equal(2)
    h.T.expect(lnd.tier2LimitSats).to.equal(50_000_000)
    h.T.expect(lnd.tier2Confs).to.equal(3)
    h.T.expect(lnd.tier3Confs).to.equal(6)

    const reloaded = new SettingsManager(h.T.storage)
    await reloaded.InitSettings()
    const persisted = reloaded.getSettings().lndSettings
    h.T.expect(persisted.tier1LimitSats).to.equal(500_000)
    h.T.expect(persisted.tier1Confs).to.equal(2)
    h.T.expect(persisted.tier2LimitSats).to.equal(50_000_000)
    h.T.expect(persisted.tier2Confs).to.equal(3)
    h.T.expect(persisted.tier3Confs).to.equal(6)
    h.T.d("update writes onchain conf tiers to memory and db")
}

const testRejectsInvalidOrdering = async (h: AdminHarness) => {
    h.T.d("starting testRejectsInvalidOrdering")
    await expectThrowsAsync(
        h.admin.UpdateAdminOnchainConfSettings(confReq({
            tier1_confs: 4,
            tier2_confs: 2,
            tier3_confs: 3,
        })),
        "onchain conf tiers",
    )
    await expectThrowsAsync(
        h.admin.UpdateAdminOnchainConfSettings(confReq({
            tier1_limit_sats: 200_000_000,
            tier2_limit_sats: 100_000_000,
        })),
        "onchain conf tiers",
    )
    const current = await h.admin.GetAdminOnchainConfSettings()
    h.T.expect(current.tier1_confs).to.equal(h.settings.getSettings().lndSettings.tier1Confs)
    h.T.d("invalid ordering is rejected without mutating settings")
}

const testEnvLockRefusesChange = async (h: AdminHarness) => {
    h.T.d("starting testEnvLockRefusesChange")
    await h.admin.UpdateAdminOnchainConfSettings(confReq({
        tier1_limit_sats: 1_000_000,
        tier1_confs: 1,
        tier2_limit_sats: 100_000_000,
        tier2_confs: 2,
        tier3_confs: 3,
    }))

    process.env[ADMIN_TIER1_CONFS_ENV] = "1"
    try {
        const locked = await h.admin.GetAdminOnchainConfSettings()
        h.T.expect(locked.tier1_confs_env_locked).to.equal(true)
        await expectThrowsAsync(
            h.admin.UpdateAdminOnchainConfSettings(confReq({ tier1_confs: 2 })),
            "onchain tier1 confs is set in the environment",
        )
        h.T.expect(h.settings.getSettings().lndSettings.tier1Confs).to.equal(1)
    } finally {
        delete process.env[ADMIN_TIER1_CONFS_ENV]
    }

    process.env[ADMIN_TIER1_LIMIT_ENV] = "1000000"
    try {
        await expectThrowsAsync(
            h.admin.UpdateAdminOnchainConfSettings(confReq({ tier1_limit_sats: 2_000_000 })),
            "onchain tier1 limit is set in the environment",
        )
        h.T.expect(h.settings.getSettings().lndSettings.tier1LimitSats).to.equal(1_000_000)
    } finally {
        delete process.env[ADMIN_TIER1_LIMIT_ENV]
    }
    h.T.d("env locks block changing onchain conf tier fields")
}

const testEnvLockAllowsUnchangedRequest = async (h: AdminHarness) => {
    h.T.d("starting testEnvLockAllowsUnchangedRequest")
    await h.admin.UpdateAdminOnchainConfSettings(confReq())
    process.env[ADMIN_TIER1_CONFS_ENV] = "1"
    try {
        const shown = await h.admin.UpdateAdminOnchainConfSettings(confReq({
            tier1_confs: 1,
            tier3_confs: 5,
        }))
        h.T.expect(shown.tier1_confs).to.equal(1)
        h.T.expect(shown.tier3_confs).to.equal(5)
        h.T.expect(h.settings.getSettings().lndSettings.tier3Confs).to.equal(5)
    } finally {
        delete process.env[ADMIN_TIER1_CONFS_ENV]
    }
    h.T.d("locked field can be echoed while unlocked fields update")
}

export default async (T: StorageTestBase) => {
    testValidationHelpers(T)
    const adminH = await setupAdminHarness(T)
    try {
        await testGetDefaults(adminH)
        await testUpdatePersists(adminH)
        await testRejectsInvalidOrdering(adminH)
        await testEnvLockRefusesChange(adminH)
        await testEnvLockAllowsUnchangedRequest(adminH)
    } finally {
        adminH.admin.Stop()
    }
}

const expectDebitFail = async (T: TestBase, promise: Promise<unknown>, code: number, error: string, extra?: Gfy6Reason | { reason?: Gfy6Reason, max?: number }) => {
    const opts = typeof extra === "string" ? { reason: extra } : extra
    let thrown: unknown
    try {
        await promise
    } catch (e) {
        thrown = e
    }
    T.expect(thrown).to.be.instanceOf(NdebitError)
    const payload = (thrown as NdebitError).getPayload()
    T.expect(payload.res).to.equal("GFY")
    T.expect(payload.code).to.equal(code)
    T.expect(payload.error).to.equal(error)
    T.expect(payload.reason).to.equal(opts?.reason)
    if (opts?.max !== undefined) {
        T.expect(payload.range?.max).to.equal(opts.max)
    }
    return payload
}


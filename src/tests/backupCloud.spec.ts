type StallMode = 'silent' | 'huge'

const startStallSftp = async (mode: StallMode) => {
    const hostKeys = utils.generateKeyPairSync('ed25519')
    const clients: Array<{ end: () => void }> = []
    const server = new Server({ hostKeys: [hostKeys.private], keepaliveInterval: 0 }, client => {
        clients.push(client)
        client.on('error', () => { /* destroyed by the client deadline */ })
        client.on('authentication', ctx => ctx.accept())
        client.on('ready', () => {
            client.on('session', (accept) => {
                const session = accept()
                session.on('sftp', (acceptSftp) => {
                    const sftp = acceptSftp()
                    // ssh2 auto-replies OP_UNSUPPORTED when emit has no listeners.
                    // Register handlers that never respond so the client's idle/op watchdog fires.
                    if (mode === 'silent') {
                        sftp.on('OPEN', () => { /* stall */ })
                        sftp.on('READ', () => { /* stall */ })
                        sftp.on('WRITE', () => { /* stall */ })
                        return
                    }
                    const handle = Buffer.alloc(4)
                    handle.writeUInt32BE(1, 0)
                    sftp.on('OPEN', (id) => sftp.handle(id, handle))
                    sftp.on('READ', (id) => sftp.data(id, Buffer.alloc(200, 7)))
                    sftp.on('CLOSE', (id) => sftp.status(id, utils.sftp.STATUS_CODE.OK))
                })
            })
        })
    })
    const port = await listenPort(server)
    return {
        port,
        stop: async () => {
            for (const c of clients) {
                try { c.end() } catch { /* already closed */ }
            }
            await new Promise<void>(resolve => server.close(() => resolve()))
        },
    }
}


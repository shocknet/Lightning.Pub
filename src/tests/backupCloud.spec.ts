const waitFor = async (pred: () => boolean, ms: number): Promise<boolean> => {
    const start = Date.now()
    while (!pred()) {
        if (Date.now() - start > ms) return false
        await new Promise<void>(resolve => setTimeout(resolve, 20))
    }
    return true
}

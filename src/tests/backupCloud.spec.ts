const leadingZeroBitsOf = (hash: Buffer): number => {
    let bits = 0
    for (const byte of hash) {
        if (byte === 0) {
            bits += 8
            continue
        }
        for (let i = 7; i >= 0; i--) {
            if (byte & (1 << i)) return bits
            bits++
        }
        return bits
    }
    return bits
}

const testLeadingZeroBits = async (T: StorageTestBase) => {
    T.d('starting testLeadingZeroBits')
    const payload = 'lightning-pub-backup'
    const hash = crypto.createHash('sha256').update(payload, 'utf8').digest()
    const zeros = leadingZeroBitsOf(hash)
    T.expect(hasLeadingZeroBits(payload, 0)).to.equal(true)
    T.expect(hasLeadingZeroBits(payload, zeros)).to.equal(true)
    T.expect(hasLeadingZeroBits(payload, zeros + 1)).to.equal(false)
    T.expect(hasLeadingZeroBits(payload, -1)).to.equal(false)
    T.expect(hasLeadingZeroBits(payload, Number.NaN)).to.equal(false)
    T.expect(hasLeadingZeroBits(payload, 1.5)).to.equal(false)
    T.d('leading-zero check matches the hash and rejects invalid bit counts')
}

const testPowDifficultyRejected = async (T: StorageTestBase) => {
    T.d('starting testPowDifficultyRejected')
    const bad = [-1, 1.5, Number.NaN, Number.POSITIVE_INFINITY, MAX_ACCEPTED_POW_BITS + 1]
    for (const bits of bad) {
        let threw = false
        try {
            assertPowDifficulty(bits)
        } catch (err: any) {
            threw = true
            T.expect(err.message).to.include('not an integer')
        }
        T.expect(threw).to.equal(true)
        let solveThrew = false
        try {
            await solvePow('challenge', bits)
        } catch (err: any) {
            solveThrew = true
            T.expect(err.message).to.include('not an integer')
        }
        T.expect(solveThrew).to.equal(true)
    }
    assertPowDifficulty(0)
    assertPowDifficulty(MAX_ACCEPTED_POW_BITS)
    T.d('proof-of-work difficulty must be an integer from 0 through the cap')
}

const testSolvePowAcceptsLowDifficulty = async (T: StorageTestBase) => {
    T.d('starting testSolvePowAcceptsLowDifficulty')
    const challenge = 'unit-test-challenge'
    const nonce = await solvePow(challenge, 8)
    T.expect(hasLeadingZeroBits(`${challenge}:${nonce}`, 8)).to.equal(true)
    T.d('solver returns a nonce that meets the requested difficulty')
}

const testHostFingerprintMatch = async (T: StorageTestBase) => {
    T.d('starting testHostFingerprintMatch')
    const hostKey = crypto.randomBytes(64)
    const raw = fingerprintOf(hostKey)
    T.expect(hostFingerprintMatches(raw, hostKey)).to.equal(true)
    T.expect(hostFingerprintMatches(`SHA256:${raw}`, hostKey)).to.equal(true)
    T.expect(hostFingerprintMatches(`SHA256:${raw}=`, hostKey)).to.equal(true)
    T.expect(hostFingerprintMatches(`  ${raw}  `, hostKey)).to.equal(true)
    const other = Buffer.from(hostKey)
    other[0] ^= 0xff
    T.expect(hostFingerprintMatches(raw, other)).to.equal(false)
    T.d('host key pin accepts ssh-keygen formatting and rejects a different key')
}

const testCustomHostPin = async (T: StorageTestBase) => {
    T.d('starting testCustomHostPin')
    T.expect(customHostFingerprint('backup.lightning.pub', 22, '')).to.equal(CLOUD_SFTP_HOST_FINGERPRINT)
    T.expect(customHostFingerprint('backup.lightning.pub', 22, ' SHA256:operator ')).to.equal('SHA256:operator')
    T.expect(customHostFingerprint('backup.lightning.pub', 2222, '')).to.equal(undefined)
    T.expect(customHostFingerprint('example.test', 22, '')).to.equal(undefined)
    T.d('managed host is pinned unless the operator set a fingerprint')
}

const testCloudErrorsAreDistinct = async (T: StorageTestBase) => {
    T.d('starting testCloudErrorsAreDistinct')
    const auth = cloudDownloadError(new SftpAuthError('SFTP login rejected by backup.lightning.pub:22'))
    const missing = failureMessage(RestoreRequest_source_type.CLOUD, 'applications')
    const ftpMissing = failureMessage(RestoreRequest_source_type.FTP_HOST, 'applications')
    const localMissing = failureMessage(RestoreRequest_source_type.LOCAL_PATH, 'applications')
    const connection = new Error('SFTP connection error: timed out')
    const mismatch = new Error('SFTP host key mismatch for backup.lightning.pub:22: expected SHA256:a, got SHA256:b. Refusing to connect.')

    T.expect(auth).to.be.instanceOf(CloudLoginRejectedError)
    T.expect(auth.message).to.include('login rejected')
    T.expect(missing).to.include('missing applications.enc')
    T.expect(missing).to.include('login succeeded')
    T.expect(auth.message).to.not.equal(missing)
    T.expect(ftpMissing).to.not.equal(missing)
    T.expect(localMissing).to.include('applications.enc')
    T.expect(cloudDownloadError(connection)).to.equal(connection)
    T.expect(cloudDownloadError(mismatch)).to.equal(mismatch)
    T.expect(cloudDownloadError('nope').message).to.include('nope')
    T.d('login rejection, missing shard, connection failure, and host-key mismatch stay distinct')
}

const testPosixRenameRequired = async (T: StorageTestBase) => {
    T.d('starting testPosixRenameRequired')
    const unsupported = { message: 'Server does not support this extended request' }
    const posix = { message: 'Server does not support posix-rename@openssh.com' }
    const opUnsupported = { message: 'Failure', code: 8 }
    const permission = { message: 'Permission denied', code: 3 }
    T.expect(isPosixRenameUnsupported(unsupported)).to.equal(true)
    T.expect(isPosixRenameUnsupported(posix)).to.equal(true)
    T.expect(isPosixRenameUnsupported(opUnsupported)).to.equal(true)
    T.expect(isPosixRenameUnsupported(permission)).to.equal(false)
    const err = new SftpIncompatibleError('sftp.example:22', 'Server does not support this extended request')
    T.expect(err).to.be.instanceOf(SftpIncompatibleError)
    T.expect(err.message).to.include('not compatible')
    T.expect(err.message).to.include('posix-rename@openssh.com')
    T.d('a server without POSIX rename is incompatible; other rename errors are not')
}

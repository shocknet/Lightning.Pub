const startAuthCountingWriteSftp = async (opts: { failOpenAt?: number, stallOpenAfter?: number } = {}) => {
    const hostKeys = utils.generateKeyPairSync('ed25519')
    const clients: Array<{ end: () => void }> = []
    let authentications = 0
    let openCount = 0
    const server = new Server({ hostKeys: [hostKeys.private], keepaliveInterval: 0 }, client => {
        clients.push(client)
        client.on('error', () => { /* client may abort */ })
        client.on('authentication', ctx => {
            authentications++
            ctx.accept()
        })
        client.on('ready', () => {
            client.on('session', (accept) => {
                const session = accept()
                session.on('sftp', (acceptSftp) => {
                    const sftp = acceptSftp()
                    const handle = Buffer.alloc(4)
                    handle.writeUInt32BE(1, 0)
                    sftp.on('OPEN', (id) => {
                        openCount++
                        if (opts.failOpenAt !== undefined && openCount === opts.failOpenAt) {
                            sftp.status(id, utils.sftp.STATUS_CODE.FAILURE)
                            return
                        }
                        if (opts.stallOpenAfter !== undefined && openCount > opts.stallOpenAfter) {
                            return
                        }
                        sftp.handle(id, handle)
                    })
                    sftp.on('WRITE', (id) => sftp.status(id, utils.sftp.STATUS_CODE.OK))
                    sftp.on('CLOSE', (id) => sftp.status(id, utils.sftp.STATUS_CODE.OK))
                })
            })
        })
    })
    const port = await listenPort(server)
    return {
        port,
        auths: () => authentications,
        opens: () => openCount,
        stop: async () => {
            for (const c of clients) {
                try { c.end() } catch { /* already closed */ }
            }
            await new Promise<void>(resolve => server.close(() => resolve()))
        },
    }
}

/** Enough of an SFTP server for one publish: reads miss, writes and deletes succeed, rename is unsupported. */
const startPublishSftp = async () => {
    const hostKeys = utils.generateKeyPairSync('ed25519')
    const clients: Array<{ end: () => void }> = []
    let authentications = 0
    let openCount = 0
    let removeCount = 0
    let nextHandle = 1
    const server = new Server({ hostKeys: [hostKeys.private], keepaliveInterval: 0 }, client => {
        clients.push(client)
        client.on('error', () => { /* client may abort */ })
        client.on('authentication', ctx => {
            authentications++
            ctx.accept()
        })
        client.on('ready', () => {
            client.on('session', (accept) => {
                const session = accept()
                session.on('sftp', (acceptSftp) => {
                    const sftp = acceptSftp()
                    const allocHandle = () => {
                        const handle = Buffer.alloc(4)
                        handle.writeUInt32BE(nextHandle++, 0)
                        return handle
                    }
                    sftp.on('OPEN', (id: number, _filename: string, flags: number) => {
                        openCount++
                        const writing = (flags & 2) !== 0
                        if (!writing) {
                            sftp.status(id, utils.sftp.STATUS_CODE.NO_SUCH_FILE)
                            return
                        }
                        sftp.handle(id, allocHandle())
                    })
                    sftp.on('WRITE', (id: number) => sftp.status(id, utils.sftp.STATUS_CODE.OK))
                    sftp.on('CLOSE', (id: number) => sftp.status(id, utils.sftp.STATUS_CODE.OK))
                    sftp.on('OPENDIR', (id: number) => sftp.handle(id, allocHandle()))
                    sftp.on('READDIR', (id: number) => sftp.status(id, utils.sftp.STATUS_CODE.EOF))
                    sftp.on('REMOVE', (id: number) => {
                        removeCount++
                        sftp.status(id, utils.sftp.STATUS_CODE.OK)
                    })
                })
            })
        })
    })
    const port = await listenPort(server)
    return {
        port,
        auths: () => authentications,
        opens: () => openCount,
        removes: () => removeCount,
        stop: async () => {
            for (const c of clients) {
                try { c.end() } catch { /* already closed */ }
            }
            await new Promise<void>(resolve => server.close(() => resolve()))
        },
    }
}


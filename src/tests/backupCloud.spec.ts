const listenPort = (server: { listen: Function, address: () => unknown, once: Function, unref?: Function }): Promise<number> => new Promise((resolve, reject) => {
    server.listen(0, '127.0.0.1', () => {
        const addr = server.address() as net.AddressInfo | string | null
        if (!addr || typeof addr === 'string') return reject(new Error('no listen port'))
        server.unref?.()
        resolve(addr.port)
    })
    server.once('error', reject)
})

const closeTracked = async (server: net.Server, sockets: Set<net.Socket>) => {
    for (const s of sockets) {
        s.destroy()
    }
    sockets.clear()
    await new Promise<void>(resolve => server.close(() => resolve()))
}


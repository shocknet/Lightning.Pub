const testHostFingerprintMatch = async (T: StorageTestBase) => {
    T.d('starting testHostFingerprintMatch')
    const hostKey = crypto.randomBytes(64)
    const raw = fingerprintOf(hostKey)
    T.expect(hostFingerprintMatches(raw, hostKey)).to.equal(true)
    T.expect(hostFingerprintMatches(`SHA256:${raw}`, hostKey)).to.equal(true)
    T.expect(hostFingerprintMatches(`SHA256:${raw}=`, hostKey)).to.equal(true)
    T.expect(hostFingerprintMatches(`  ${raw}  `, hostKey)).to.equal(true)
    const other = Buffer.from(hostKey)
    other[0] ^= 0xff
    T.expect(hostFingerprintMatches(raw, other)).to.equal(false)
    T.d('host key pin accepts ssh-keygen formatting and rejects a different key')
}


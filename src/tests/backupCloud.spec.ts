const testSftpSessionAbortWaitsForCallback = async (T: StorageTestBase) => {
    T.d('starting testSftpSessionAbortWaitsForCallback')
    const { port, stop, opens } = await startAuthCountingWriteSftp({ stallOpenAfter: 1 })
    let releaseFn: () => void = () => { }
    const hold = new Promise<void>(resolve => { releaseFn = resolve })
    let reachedHold = false
    let thirdMs = -1
    let outerSettled = false
    const cfg = sftpCfg(port, { idleTimeoutMs: 200, opTimeoutMs: 5000 })
    const payload = Buffer.from('shard')
    const work = withSftpSession(cfg, async session => {
        await session.upload('a.enc', payload)
        let second: unknown
        try {
            await session.upload('b.enc', payload)
        } catch (err) {
            second = err
        }
        T.expect(second).to.be.instanceOf(SftpTimeoutError)
        const started = Date.now()
        let third: unknown
        try {
            await session.upload('c.enc', payload)
        } catch (err) {
            third = err
        }
        thirdMs = Date.now() - started
        T.expect(third).to.be.instanceOf(SftpTimeoutError)
        reachedHold = true
        await hold
    })
    work.then(() => { outerSettled = true }, () => { outerSettled = true })
    try {
        const sawHold = await waitFor(() => reachedHold, 2000)
        T.expect(sawHold).to.equal(true)
        T.expect(thirdMs).to.be.lessThan(500)
        T.expect(opens()).to.equal(2)
        await new Promise<void>(resolve => setTimeout(resolve, 50))
        T.expect(outerSettled).to.equal(false)
        releaseFn()
        let err: unknown
        try {
            await work
        } catch (e) {
            err = e
        }
        T.expect(err).to.be.instanceOf(SftpTimeoutError)
        T.expect(outerSettled).to.equal(true)
    } finally {
        releaseFn()
        await stop()
    }
    T.d('an idle timeout fails later calls immediately and waits until the callback returns')
}


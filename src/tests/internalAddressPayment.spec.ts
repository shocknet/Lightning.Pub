import { randomBytes } from 'crypto'
import * as Types from '../../proto/autogenerated/ts/types.js'
import { expect, expectThrowsAsync, runSanityCheck, safelySetUserBalance, TestBase } from './testBase.js'
export const ignore = false
export const dev = false

const userContext = (T: TestBase, user: TestBase["user1"]): Types.UserContext => ({
    app_id: T.app.appId,
    app_user_id: user.appUserIdentifier,
    user_id: user.userId,
})

export default async (T: TestBase) => {
    await safelySetUserBalance(T, T.user1, 2000)
    await testSuccessfulInternalAddressPayment(T)
    await testInternalPayKeepsStartedReverseSwap(T)
    await testInternalPayDeletesUnusedReverseSwapQuote(T)
    await testFailedInternalAddressPayment(T)
    await testSanityCheckAllowsDeletedUserAddress(T)
    await runSanityCheck(T)
}

const testSuccessfulInternalAddressPayment = async (T: TestBase) => {
    T.d("starting testSuccessfulInternalAddressPayment")
    const user2Address = await T.main.paymentManager.NewAddress(userContext(T, T.user2), { addressType: Types.AddressType.WITNESS_PUBKEY_HASH })
    expect(user2Address.address).to.startWith("bcrt1")
    T.d("generated internal chain address for user2")

    const pay = await T.main.paymentManager.PayAddress(userContext(T, T.user1), {
        address: user2Address.address,
        amountSats: 1000,
        satsPerVByte: 1,
    })
    expect(pay.txId).to.not.be.undefined
    expect(pay.network_fee).to.be.equal(0)
    expect(pay.service_fee).to.be.equal(6)
    expect(pay.operation_id).to.startWith(`${Types.UserOperationType.OUTGOING_TX}-`)
    T.d("paid 1000 sats to user2's internal address from user1")

    const application = await T.main.storage.applicationStorage.GetApplication(T.app.appId)
    const u1 = await T.main.storage.userStorage.GetUser(T.user1.userId)
    const u2 = await T.main.storage.userStorage.GetUser(T.user2.userId)
    const owner = await T.main.storage.userStorage.GetUser(application.owner.user_id)
    expect(u2.balance_sats).to.be.equal(1000)
    T.d("user2 balance is 1000")
    expect(u1.balance_sats).to.be.equal(994)
    T.d("user1 balance is 994 cuz he paid 6 sats fee")
    expect(owner.balance_sats).to.be.equal(6)
    T.d("app balance is 6 sats")

    const outgoingTx = await T.main.storage.paymentStorage.GetUserTransactionPaymentOwner(user2Address.address, pay.txId)
    expect(outgoingTx?.internal).to.be.true
    const incomingTx = await T.main.storage.paymentStorage.GetAddressReceivingTransactionOwner(user2Address.address, pay.txId, 0)
    expect(incomingTx?.internal).to.be.true
    T.d("payment is recorded as internal in storage")
}

const reverseSwapQuote = (T: TestBase, extra: Record<string, unknown> = {}) => ({
    app_user_id: T.user1.appUserIdentifier,
    swap_quote_id: `swap-${randomBytes(8).toString('hex')}`,
    swap_tree: '{}',
    lockup_address: 'bcrt1qlockup',
    refund_public_key: '11'.repeat(33),
    timeout_block_height: 920_000 + 1_008,
    invoice: 'lnbc1-rev',
    invoice_amount: 1200,
    transaction_amount: 1000,
    swap_fee_sats: 50,
    chain_fee_sats: 15,
    preimage: '22'.repeat(32),
    ephemeral_public_key: '33'.repeat(33),
    ephemeral_private_key: '44'.repeat(32),
    service_url: 'http://mock-boltz',
    ...extra,
})

const testInternalPayKeepsStartedReverseSwap = async (T: TestBase) => {
    T.d("starting testInternalPayKeepsStartedReverseSwap")
    const started = await T.main.storage.paymentStorage.AddTransactionSwap(reverseSwapQuote(T, {
        paid_at_unix: 1,
        address_paid: 'bcrt1qexternal',
        lockup_tx_hex: '020000000001aabb',
    }))
    const user2Address = await T.main.paymentManager.NewAddress(userContext(T, T.user2), { addressType: Types.AddressType.WITNESS_PUBKEY_HASH })
    await expectThrowsAsync(T.main.paymentManager.PayAddress(userContext(T, T.user1), {
        address: user2Address.address,
        amountSats: 200,
        satsPerVByte: 1,
        swap_operation_id: started.swap_operation_id,
    }), "cannot pay an internal address with a started swap")
    const leftover = await T.main.storage.paymentStorage.GetTransactionSwap(started.swap_operation_id, T.user1.appUserIdentifier)
    expect(leftover).to.not.equal(null)
    expect(leftover?.lockup_tx_hex).to.equal('020000000001aabb')
    await T.main.storage.paymentStorage.DeleteTransactionSwap(started.swap_operation_id)
    T.d("started reverse swap was kept when paying an internal address")
}

const testInternalPayDeletesUnusedReverseSwapQuote = async (T: TestBase) => {
    T.d("starting testInternalPayDeletesUnusedReverseSwapQuote")
    const quote = await T.main.storage.paymentStorage.AddTransactionSwap(reverseSwapQuote(T))
    const user2Address = await T.main.paymentManager.NewAddress(userContext(T, T.user2), { addressType: Types.AddressType.WITNESS_PUBKEY_HASH })
    const pay = await T.main.paymentManager.PayAddress(userContext(T, T.user1), {
        address: user2Address.address,
        amountSats: 200,
        satsPerVByte: 1,
        swap_operation_id: quote.swap_operation_id,
    })
    expect(pay.txId).to.not.be.undefined
    const leftover = await T.main.storage.paymentStorage.GetTransactionSwap(quote.swap_operation_id, T.user1.appUserIdentifier)
    expect(leftover).to.equal(null)
    T.d("unused reverse swap quote was discarded on internal pay")
}


const testHookEnrollCreate = async (T: StorageTestBase) => {
    T.d('starting testHookEnrollCreate')
    const settings = new SettingsManager(T.storage)
    await settings.InitSettings()
    settings.OverrideTestSettings(s => {
        s.nostrRelaySettings.enrollPowBits = 0
        if (!s.nostrRelaySettings.relays[0]) {
            s.nostrRelaySettings.relays = ['wss://relay.lightning.pub']
        }
        return s
    })
    const spy = makeSpyBackup()
    const enroll = new EnrollManager(T.storage, settings, spy)
    const app = await T.storage.applicationStorage.AddApplication(`enroll-backup-${Date.now()}`, true)
    const keys = await T.storage.applicationStorage.GenerateApplicationKeys(app)
    const pub = 'e'.repeat(64)
    const ctx = toClinkCtx({
        id: 'f'.repeat(64),
        pub,
        content: '{}',
        appId: keys.appId,
        startAtNano: '0',
        startAtMs: Date.now(),
        kind: CLINK_ENROLL_KIND,
        tags: [['p', keys.publicKey], ['clink_version', CLINK_VERSION]],
        created_at: Math.floor(Date.now() / 1000),
    })
    const ok = await enroll.HandleClinkEnroll(ctx, {})
    T.expect(ok?.res).to.equal('ok')
    T.expect(spy.notified).to.include('application_users')
    T.expect(spy.notified).to.include('user_balances')
    T.d('enroll create notifies application_users and user_balances')
}

const seedDialtone = async (T: StorageTestBase, settings: SettingsManager) => {
    const defaultName = settings.getSettings().serviceSettings.defaultAppName
    let app = pickDefaultApp(await T.storage.applicationStorage.GetApplications(), defaultName)
    if (!app) {
        app = await T.storage.applicationStorage.AddApplication(defaultName, true)
    }
    await T.storage.applicationStorage.GenerateApplicationKeys(app)
    app = await T.storage.applicationStorage.GetApplication(app.app_id)

    const user = await T.storage.applicationStorage.AddApplicationUser(app, crypto.randomBytes(32).toString('hex'), 1234)
    await T.storage.applicationStorage.UpdateAppUserMessagingToken(user.identifier, 'aa'.repeat(16), 'token-1')
    await T.storage.offerStorage.AddDefaultUserOffer(user.identifier)
    await T.storage.productStorage.AddProduct('backup-product', 50, user.user)
    await T.storage.debitStorage.AddDebitAccess(user.identifier, {
        npub: 'b'.repeat(64),
        authorize: true,
    })
    await T.storage.managementStorage.addGrant(user.identifier, 'c'.repeat(64), false, 0)
    await T.storage.applicationStorage.AddInviteToken(app, 100)
    await T.storage.liquidityStorage.CreateTrackedProvider('lnPub', 'd'.repeat(64), 42)
    await settings.updateLspChannelThreshold(1_500_000)

    return { app, user }
}

const testLocalRoundtrip = async (T: StorageTestBase) => {
    T.d('starting testLocalRoundtrip')
    const dir = tempBackupDir()
    const settings = new SettingsManager(T.storage)
    await settings.InitSettings()
    settings.OverrideTestSettings(s => {
        s.backupSettings.localPath = dir
        s.backupSettings.cloudEnabled = false
        s.backupSettings.sftpEnabled = false
        return s
    })

    const backup = new BackupManager(T.storage, settings)
    await backup.InitKeys(TEST_SEED)
    settings.setBackupManager(backup)

    const { app, user } = await seedDialtone(T, settings)
    await backup.AddressUpdate(17)
    await backup.shutdown()

    const expectedFiles = BACKUP_TABLE_IDS.map(backupTableFilename).sort()
    T.expect(listEncFiles(dir)).to.deep.equal(expectedFiles)

    const before = {
        applications: sortBy(await T.storage.applicationStorage.ExportApplications(), r => r.app_id),
        applicationUsers: sortBy(await T.storage.applicationStorage.ExportApplicationUsers(), r => r.identifier),
        balances: sortBy(await T.storage.userStorage.ExportBalances(), r => r.user_id),
        adminSettings: sortBy(await T.storage.settingsStorage.ExportSettings(), r => r.env_name),
        userOffers: sortBy(await T.storage.offerStorage.ExportUserOffers(), r => r.offer_id),
        products: sortBy(await T.storage.productStorage.ExportProducts(), r => r.product_id),
        debitAccesses: sortBy(await T.storage.debitStorage.ExportDebitAccess(), r => `${r.app_user_id}:${r.npub}`),
        managementGrants: sortBy(await T.storage.managementStorage.ExportManagementGrants(), r => `${r.app_user_id}:${r.app_pubkey}`),
        inviteTokens: sortBy(await T.storage.applicationStorage.ExportInviteTokens(), r => r.inviteToken),
        appUserDevices: sortBy(await T.storage.applicationStorage.ExportAppUserDevices(), r => `${r.app_user_id}:${r.device_id}`),
        trackedProviders: sortBy(await T.storage.liquidityStorage.ExportTrackedProviders(), r => `${r.provider_type}:${r.provider_pubkey}`),
    }
    T.expect(before.applications.some(a => a.app_id === app.app_id && !!a.nostr_public_key)).to.equal(true)
    T.expect(before.balances.some(b => b.user_id === user.user.user_id && b.balance_sats === 1234)).to.equal(true)
    T.expect(before.adminSettings.some(s => s.env_name === 'LSP_CHANNEL_THRESHOLD' && s.env_value === '1500000')).to.equal(true)

    const dest = await openSecondStorage()
    T.expect(await dest.IsDbClean()).to.equal(true)
    const destSettings = new SettingsManager(dest)
    await destSettings.InitSettings()
    const restore = new RestoreManager(dest, destSettings, {} as Unlocker)
    const keys = await deriveBackupKeys(TEST_PHRASE)
    const req: WizardTypes.RestoreRequest = {
        phrase: TEST_PHRASE,
        source: { type: WizardTypes.RestoreRequest_source_type.LOCAL_PATH, local_path: dir },
    }
    const buffers = await restore.fetchSegmentsData(req, keys)
    T.expect(buffers.size).to.equal(BACKUP_TABLE_IDS.length)
    const { backupData } = restore.decodeSegmentsData(buffers, keys)
    T.expect(backupData.indexes[0]?.addressesCount).to.equal(17)

    await dest.StartTransaction(async tx => {
        await restore.importDialtone(backupData, tx)
    }, 'backup-local-restore')

    const after = {
        applications: sortBy(await dest.applicationStorage.ExportApplications(), r => r.app_id),
        applicationUsers: sortBy(await dest.applicationStorage.ExportApplicationUsers(), r => r.identifier),
        balances: sortBy(await dest.userStorage.ExportBalances(), r => r.user_id),
        adminSettings: sortBy(await dest.settingsStorage.ExportSettings(), r => r.env_name),
        userOffers: sortBy(await dest.offerStorage.ExportUserOffers(), r => r.offer_id),
        products: sortBy(await dest.productStorage.ExportProducts(), r => r.product_id),
        debitAccesses: sortBy(await dest.debitStorage.ExportDebitAccess(), r => `${r.app_user_id}:${r.npub}`),
        managementGrants: sortBy(await dest.managementStorage.ExportManagementGrants(), r => `${r.app_user_id}:${r.app_pubkey}`),
        inviteTokens: sortBy(await dest.applicationStorage.ExportInviteTokens(), r => r.inviteToken),
        appUserDevices: sortBy(await dest.applicationStorage.ExportAppUserDevices(), r => `${r.app_user_id}:${r.device_id}`),
        trackedProviders: sortBy(await dest.liquidityStorage.ExportTrackedProviders(), r => `${r.provider_type}:${r.provider_pubkey}`),
    }

    // Dest InitSettings may add extra admin_settings rows; assert source rows are present.
    for (const row of before.adminSettings) {
        const found = after.adminSettings.find(s => s.env_name === row.env_name)
        T.expect(found?.env_value).to.equal(row.env_value)
    }
    T.expect(after.applications).to.deep.equal(before.applications)
    T.expect(after.applicationUsers).to.deep.equal(before.applicationUsers)
    T.expect(after.balances).to.deep.equal(before.balances)
    T.expect(after.userOffers).to.deep.equal(before.userOffers)
    T.expect(after.products).to.deep.equal(before.products)
    T.expect(after.debitAccesses).to.deep.equal(before.debitAccesses)
    T.expect(after.managementGrants).to.deep.equal(before.managementGrants)
    T.expect(after.inviteTokens).to.deep.equal(before.inviteTokens)
    T.expect(after.appUserDevices).to.deep.equal(before.appUserDevices)
    T.expect(after.trackedProviders).to.deep.equal(before.trackedProviders)

    dest.Stop()
    fs.rmSync(dir, { recursive: true, force: true })
    T.d('local backup shards restore dialtone state')
}


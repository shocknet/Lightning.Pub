type SpyBackup = BackupManager & { notified: BackupTableId[] }

const makeSpyBackup = (): SpyBackup => {
    const notified: BackupTableId[] = []
    const spy = {
        notified,
        notifyBackupTable: async (...ids: BackupTableId[]) => {
            notified.push(...ids)
        },
    }
    return spy as SpyBackup
}


import {
    ADMIN_AUTOMATION_ENV,
    ADMIN_LSP_THRESHOLD_ENV,
    DEFAULT_LSP_CHANNEL_THRESHOLD,
    MAX_NODE_NAME_LEN,
    automationEnabled,
    disableLiquidityFromAutomation,
    isHttpsAvatarUrl,
    isValidLspThreshold,
    isValidNodeName,
    lspAutoBuyEnabled,
    persistLspThreshold,
    pickDefaultApp,
} from "../services/main/adminNodeSettings.js"

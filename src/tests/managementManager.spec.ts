const runManageTransport = async (T: TestBase, event: NostrEvent) => {
    const sent: UnsignedEvent[] = []
    const transport = newClinkTransport(newClinkRouter(T.main))
    await transport(event, e => { sent.push(e) })
    return sent
}

const withCapturedNostrSends = async <R>(
    storage: Storage,
    fn: (sent: SendData[]) => Promise<R>,
): Promise<R> => {
    const sent: SendData[] = []
    const sender = storage.NostrSender()
    const originalSend = sender.Send.bind(sender)
    sender.Send = (_initiator, data) => { sent.push(data) }
    try {
        return await fn(sent)
    } finally {
        sender.Send = originalSend
    }
}


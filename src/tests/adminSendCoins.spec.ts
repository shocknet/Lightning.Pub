import * as Types from "../../proto/autogenerated/ts/types.js"
import {
    expectThrowsAsync,
    runSanityCheck,
    safelySetUserBalance,
    TestBase,
    waitForLndSynced,
} from "./testBase.js"
import { waitForLndSync } from "./lndSync.js"
import { tryUntil } from "./networkSetup.js"
import { spendExceedsNodeSurplus } from "../services/main/adminManager.js"

export const ignore = false
export const dev = false

const FUND_SATS = 50_000
const SEND_SATS = 5_000

export default async (T: TestBase) => {
    await safelySetUserBalance(T, T.user1, 2000)
    await fundPubOnchain(T, FUND_SATS)
    await testAdminSendCoinsSuccess(T)
    await testAdminSendCoinsSurplusCheck(T)
    await testAdminSendCoinsOutgoingOpsLocked(T)
    await testAdminSendCoinsValidation(T)
    await runSanityCheck(T)
}

const fundPubOnchain = async (T: TestBase, amount: number) => {
    T.d(`funding pub on-chain with ${amount} sats`)
    const before = await T.main.lnd.GetBalance()
    const addr = await T.main.lnd.NewAddress(Types.AddressType.WITNESS_PUBKEY_HASH, { useProvider: false, from: 'system' })
    const { blockHeight: beforePay } = await T.main.lnd.GetInfo()
    await waitForLndSync(T.externalAccessToOtherLnd, beforePay)
    const payment = await T.externalAccessToOtherLnd.PayAddress(addr.address, amount, 2, "admin-send-fund", { useProvider: false, from: 'system' })
    T.expect(payment.txid).to.be.a("string")
    await T.chainTools.mine(1)
    await waitForLndSynced(T.main.lnd, 30_000, beforePay + 1)
    await tryUntil(async () => {
        const bal = await T.main.lnd.GetBalance()
        if (bal.confirmedBalance < before.confirmedBalance + amount) {
            throw new Error(`waiting for confirmed balance: ${bal.confirmedBalance}`)
        }
        return bal
    }, 30, 500)
    T.d("pub on-chain funded")
}

const testAdminSendCoinsSuccess = async (T: TestBase) => {
    T.d("starting testAdminSendCoinsSuccess")
    const u1Before = await T.main.storage.userStorage.GetUser(T.user1.userId)
    const u2Before = await T.main.storage.userStorage.GetUser(T.user2.userId)
    const dest = await T.externalAccessToOtherLnd.NewAddress(Types.AddressType.WITNESS_PUBKEY_HASH, { useProvider: false, from: 'system' })

    const res = await T.main.adminManager.AdminSendCoins({
        address: dest.address,
        amount: SEND_SATS,
        sat_per_v_byte: 2,
    })
    T.expect(Types.AdminSendCoinsResponseValidate(res)).to.equal(null)
    T.expect(res.tx_id).to.be.a("string").and.not.equal("")
    T.expect(res.amount).to.equal(SEND_SATS)
    T.expect(res.network_fee).to.be.a("number").and.greaterThan(0)

    const root = await T.main.storage.metricsStorage.GetRootOperation("chain_payment", res.tx_id)
    T.expect(!!root).to.equal(true)
    T.expect(root!.pending).to.equal(true)
    T.expect(root!.operation_amount).to.equal(SEND_SATS + res.network_fee)

    const u1After = await T.main.storage.userStorage.GetUser(T.user1.userId)
    const u2After = await T.main.storage.userStorage.GetUser(T.user2.userId)
    T.expect(u1After.balance_sats).to.equal(u1Before.balance_sats)
    T.expect(u2After.balance_sats).to.equal(u2Before.balance_sats)

    const userTx = await T.main.storage.paymentStorage.GetTxHashPaymentOwner(res.tx_id)
    T.expect(userTx).to.equal(null)

    const { blockHeight: beforeMine, identityPubkey } = await T.main.lnd.GetInfo()
    await T.chainTools.mine(1)
    const afterMine = await waitForLndSync(T.main.lnd, beforeMine + 1)

    const assets = await T.main.adminManager.GetAssetsAndLiabilitiesV2({
        lnd_providers: [{
            pubkey: identityPubkey,
            limit_transactions: 50,
            tx_start_height: afterMine.blockHeight,
        }],
        liquidity_providers: [],
    })
    const lnd = assets.lnds.find(p => p.pubkey === identityPubkey)
    T.expect(lnd?.tracked).to.not.equal(undefined)
    const tracked = lnd!.tracked!.outgoing_tx.operations.find(op =>
        op.tracked?.type === Types.TrackedOperationType.ROOT
        && op.tracked.amount === SEND_SATS + res.network_fee
    )
    T.expect(tracked).to.not.equal(undefined)
    T.d("admin send recorded pending chain_payment and left user balances untouched")
}

const testAdminSendCoinsSurplusCheck = async (T: TestBase) => {
    T.d("starting testAdminSendCoinsSurplusCheck")
    // The test node has channel capacity well above users_balance, so a fundable
    // on-chain send cannot actually breach surplus. Check the rule directly.
    T.expect(spendExceedsNodeSurplus(1_001, 10_000, 9_000)).to.equal(true)
    T.expect(spendExceedsNodeSurplus(1_000, 10_000, 9_000)).to.equal(false)
    T.expect(spendExceedsNodeSurplus(50_000, 200_000, 2_000)).to.equal(false)
    T.d("surplus comparison treats spend above assets minus users as user-custodied")
}

const testAdminSendCoinsOutgoingOpsLocked = async (T: TestBase) => {
    T.d("starting testAdminSendCoinsOutgoingOpsLocked")
    const dest = await T.externalAccessToOtherLnd.NewAddress(Types.AddressType.WITNESS_PUBKEY_HASH, { useProvider: false, from: 'system' })
    T.main.lnd.LockOutgoingOperations()
    try {
        await expectThrowsAsync(
            T.main.adminManager.AdminSendCoins({
                address: dest.address,
                amount: 1000,
                sat_per_v_byte: 2,
            }),
            "lnd node is currently out of sync",
        )
    } finally {
        T.main.lnd.UnlockOutgoingOperations()
    }
    T.d("outgoingOpsLocked blocked admin send")
}

const testAdminSendCoinsValidation = async (T: TestBase) => {
    T.d("starting testAdminSendCoinsValidation")
    await expectThrowsAsync(
        T.main.adminManager.AdminSendCoins({
            address: "",
            amount: 1000,
        }),
        "address is required",
    )
    await expectThrowsAsync(
        T.main.adminManager.AdminSendCoins({
            address: "bcrt1qvalidation",
            send_all: true,
            amount: 1000,
        }),
        "amount must be omitted when send_all is set",
    )
    await expectThrowsAsync(
        T.main.adminManager.AdminSendCoins({
            address: "bcrt1qvalidation",
        }),
        "amount must be a positive integer number of sats unless send_all is set",
    )

    const userAddr = await T.main.paymentManager.NewAddress(
        { app_id: T.app.appId, app_user_id: T.user1.appUserIdentifier, user_id: T.user1.userId },
        { addressType: Types.AddressType.WITNESS_PUBKEY_HASH },
    )
    await expectThrowsAsync(
        T.main.adminManager.AdminSendCoins({
            address: userAddr.address,
            amount: 1000,
            sat_per_v_byte: 2,
        }),
        "cannot send to a user deposit address via admin send",
    )
    T.d("admin send validation rejects bad requests")
}

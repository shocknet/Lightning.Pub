import * as Types from "../../proto/autogenerated/ts/types.js"
import { DebitManager } from "../services/CLINK/debitManager.js"
import { gfy6Reason, invoiceAlreadyFailedReason, invoiceAlreadyPaidReason, invoicePaymentInProgressReason, validateDebitReq } from "../services/CLINK/debitTypes.js"
import PaymentManager from "../services/main/paymentManager.js"
import { newClinkTransport } from "../services/serverMethods/clinkTransport.js"
import { NostrEvent } from "../services/nostr/nostrPool.js"
import { StorageTestBase } from "./testBase.js"

export const ignore = false
export const dev = false
export const requires = "storage" as const

export default async (T: StorageTestBase) => {
    const app = await T.storage.applicationStorage.AddApplication("preauth replay", true)
    const appUser = await T.storage.applicationStorage.AddApplicationUser(app, "preauth-seller", 0, "b".repeat(64))
    const pub = "a".repeat(64)
    T.expect(await T.storage.debitStorage.GetDebitAccess(appUser.identifier, pub)).to.equal(null)

    const incoming = await T.storage.paymentStorage.AddUserInvoice(appUser.user, "lnbcrt1paid-internal", { expiry: 3600 })
    await T.storage.StartTransaction(tx => T.storage.paymentStorage.FlagInvoiceAsPaid(incoming, 100, 0, true, tx))
    for (const state of ["paid", "failed", "pending"]) {
        const payment = await T.storage.StartTransaction(tx => T.storage.paymentStorage.AddPendingExternalPayment(
            appUser.user.user_id, `lnbcrt1${state}-external`, { payAmount: 100, serviceFee: 0, networkFee: 0 }, app, undefined, tx,
        ))
        if (state !== "pending") {
            await T.storage.paymentStorage.UpdateExternalPayment(payment.serial_id, 0, 0, state === "paid")
        }
    }

    let prompts = 0
    let notifications = 0
    const storage = Object.assign(Object.create(T.storage), {
        NostrSender: () => ({ Send: () => { prompts++ } }),
    }) as typeof T.storage
    // Exercise the real database conflict check without a Lightning node or payment attempt.
    const paymentManager = Object.assign(Object.create(PaymentManager.prototype), {
        storage: T.storage,
        invoiceLock: { tryLock: () => true, unlock: () => { } },
    }) as PaymentManager
    const manager = new DebitManager(storage, {} as DebitManager["lnd"], {} as DebitManager["applicationManager"], paymentManager,
        { SendEncryptedPayload: async () => { notifications++ } } as unknown as DebitManager["notificationsManager"], {} as DebitManager["backupManager"])
    const transport = newClinkTransport(async (ctx, _kind, req) => {
        const data = validateDebitReq(req)
        await manager.handleAuthRequired(data, ctx, {
            app, appUser,
            liveDebitReq: {
                request_id: ctx.eventId, npub: ctx.pub, k1: data.k1,
                debit: { type: Types.LiveDebitRequest_debit_type.INVOICE, invoice: data.bolt11! },
            },
        })
        return null
    })
    try {
        const cases = [
            ["lnbcrt1paid-internal", gfy6Reason.invoiceAlreadyPaid, invoiceAlreadyPaidReason],
            ["lnbcrt1paid-external", gfy6Reason.invoiceAlreadyPaid, invoiceAlreadyPaidReason],
            ["lnbcrt1failed-external", gfy6Reason.invoiceAlreadyFailed, invoiceAlreadyFailedReason],
            ["lnbcrt1pending-external", gfy6Reason.invoiceInProgress, invoicePaymentInProgressReason],
        ]
        for (const [index, [invoice, reason, message]] of cases.entries()) {
            const k1 = (index + 1).toString(16).padStart(64, "0")
            for (const uppercase of [false, true]) {
                const event: NostrEvent = {
                    id: `preauth-${index}-${uppercase}`, pub, appId: app.app_id, kind: 21002,
                    content: JSON.stringify({ pointer: appUser.identifier, bolt11: uppercase ? invoice.toUpperCase() : invoice, k1 }),
                    startAtNano: "0", startAtMs: Date.now(),
                }
                const replies: { kind: number, tags: string[][], body: unknown }[] = []
                await transport(event, response => {
                    replies.push({ kind: response.kind, tags: response.tags, body: JSON.parse(response.content) })
                })
                T.expect(replies).to.have.length(1)
                T.expect(replies[0].kind).to.equal(21002)
                T.expect(replies[0].tags).to.deep.include(["p", pub])
                T.expect(replies[0].tags).to.deep.include(["e", event.id])
                T.expect(replies[0].body).to.deep.equal({ res: "GFY", code: 6, error: `Invalid Request: ${message}`, reason })
                T.expect(await T.storage.debitStorage.findActiveK1(app.app_id, appUser.identifier, k1)).to.equal(null)
                T.expect(manager.authGate.matchesPending(appUser.identifier, pub, event.id)).to.equal(false)
            }
        }
        T.expect(prompts).to.equal(0)
        T.expect(notifications).to.equal(0)
        T.expect((await T.storage.userStorage.GetUser(appUser.user.user_id)).balance_sats).to.equal(0)
        T.d("pre-authorization paid, failed, and pending invoice replays return GFY 6 reason tokens without prompting or holding k1")
    } finally {
        manager.Stop()
    }
}

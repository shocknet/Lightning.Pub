import assert from 'node:assert/strict'
import { Transaction as BitcoinTransaction } from 'bitcoinjs-lib'
import { UtxoOrigin, LndUtxosValidate } from '../../proto/autogenerated/ts/types.js'
import { OutputDetail, OutPoint } from '../../proto/lnd/lightning.js'
import { classifyUtxos, OriginTransaction } from '../services/helpers/utxoOrigin.js'
import { loadUtxoClassification } from '../services/main/utxoClassification.js'
import type LND from '../services/lnd/lnd.js'
import type Storage from '../services/storage/index.js'

export const ignore = false
export const dev = false
export const requires = 'storage' as const

const output = (address: string, index = 0, ours = true) => OutputDetail.create({
    address, outputIndex: BigInt(index), isOurAddress: ours, amount: 100n,
})
const tx = (hash: string, inputs: string[] = [], outputs = [output('change')]): OriginTransaction => ({
    txHash: hash, rawTxHex: '', previousOutpoints: inputs.map(outpoint => ({ outpoint, isOurOutput: true })), outputDetails: outputs,
})
const classify = (txs: OriginTransaction[], channelTxids: string[] = []) => classifyUtxos(
    txs, new Set(['user-address']), new Set(['recorded:0']), new Set(channelTxids), new Set(['change']),
)

export default async () => {
    // Match individual outputs, never every output in a user's deposit tx.
    let result = classify([tx('deposit', [], [output('user-address'), output('operator', 1)]), tx('recorded')])
    assert.equal(result.get('deposit:0')?.origin, UtxoOrigin.USER_DEPOSIT)
    assert.equal(result.get('deposit:1')?.origin, UtxoOrigin.UNKNOWN)
    assert.equal(result.get('recorded:0')?.origin, UtxoOrigin.USER_DEPOSIT)

    const deposit = tx('deposit', [], [output('user-address')])
    const withdrawal = tx('withdrawal', ['deposit:0'])
    const open = tx('open', ['withdrawal:0'])
    const close = tx('close')
    const sweep = tx('sweep', ['missing-htlc:0'])
    // Deliberately reverse dependency order, as LND can return mempool children first.
    result = classify([tx('channel-change', ['open:0']), open, withdrawal, deposit, close, sweep], ['open', 'close', 'sweep'])
    assert.deepEqual(result.get('withdrawal:0'), { origin: UtxoOrigin.USER_DEPOSIT, is_change: true })
    for (const hash of ['open', 'close', 'sweep', 'channel-change']) assert.equal(result.get(`${hash}:0`)?.origin, UtxoOrigin.CHANNEL)

    result = classify([deposit, close, tx('mixed', ['deposit:0', 'close:0']), tx('mixed-change', ['mixed:0']),
        tx('unknown', ['deposit:0', 'missing-wallet:0'])], ['close'])
    assert.equal(result.get('mixed:0')?.origin, UtxoOrigin.MIXED)
    assert.equal(result.get('mixed-change:0')?.origin, UtxoOrigin.MIXED)
    assert.equal(result.get('unknown:0')?.origin, UtxoOrigin.UNKNOWN)

    // A force-close can pass through non-wallet-owned intermediate outputs.
    const intermediate = tx('intermediate', ['close:0'], [output('', 0, false)])
    intermediate.previousOutpoints[0].isOurOutput = false
    const finalSweep = tx('final-sweep', ['intermediate:0'])
    finalSweep.previousOutpoints[0].isOurOutput = false
    result = classify([finalSweep, intermediate, tx('close', [], [output('', 0, false)])], ['close'])
    assert.equal(result.get('final-sweep:0')?.origin, UtxoOrigin.CHANNEL)

    // Old LND versions can supply raw hex without previous_outpoints.
    const parent = 'ab'.repeat(32)
    const raw = new BitcoinTransaction()
    raw.addInput(Buffer.from(parent, 'hex').reverse(), 0)
    raw.addOutput(Buffer.from('0014' + '00'.repeat(20), 'hex'), 99)
    const legacy = tx('legacy')
    legacy.rawTxHex = raw.toHex()
    result = classify([legacy, tx(parent, [], [output('user-address')])])
    assert.equal(result.get('legacy:0')?.origin, UtxoOrigin.USER_DEPOSIT)
    assert.equal(classify([legacy]).get('legacy:0')?.origin, UtxoOrigin.UNKNOWN)

    // No recursion limit for long-running wallets with many generations of change.
    const chain = [deposit]
    for (let i = 0; i < 5000; i++) chain.push(tx(`change-${i}`, [i ? `change-${i - 1}:0` : 'deposit:0']))
    assert.equal(classify(chain.reverse()).get('change-4999:0')?.origin, UtxoOrigin.USER_DEPOSIT)

    await testHistoricalSources()
    // Optional additions preserve transport validation for old nodes/clients.
    const coin = { address: 'a', txid: 't', output_index: 0, amount_sat: 100, confirmations: 0 }
    assert.equal(LndUtxosValidate({ utxos: [coin] }), null)
    assert.equal(LndUtxosValidate({ utxos: [{ ...coin, origin: UtxoOrigin.CHANNEL, is_change: true }] }), null)
}

async function testHistoricalSources() {
    const hashes = ['open', 'closed-funding', 'close', 'resolution', 'pending-open', 'pending-close-funding', 'pending-close',
        'force-funding', 'force-close', 'waiting-funding', 'waiting-close', 'sweep']
    const pending = (hash: string) => ({ channel: { channelPoint: `${hash}-funding:1` }, closingTxid: `${hash}-close` })
    const lnd = {
        GetTransactions: async (start: number) => {
            assert.equal(start, 0)
            return { transactions: [...hashes.map(hash => tx(hash)), tx('deposit', [], [output('user-address')]), tx('recorded')] }
        },
        ListChannels: async () => ({ channels: [{ channelPoint: 'open:0' }] }),
        ListClosedChannels: async () => ({ channels: [{ channelPoint: 'closed-funding:0', closingTxHash: 'close', resolutions: [{ sweepTxid: 'resolution' }] }] }),
        ListPendingChannels: async () => ({
            pendingOpenChannels: [{ channel: { channelPoint: 'pending-open:0' } }],
            pendingClosingChannels: [{ channel: { channelPoint: 'pending-close-funding:0' }, closingTxid: 'pending-close' }],
            pendingForceClosingChannels: [pending('force')], waitingCloseChannels: [pending('waiting')],
        }),
        ListSweeps: async () => ['sweep'],
        ListAddresses: async () => [{ address: 'change', change: true }],
    } as unknown as LND
    const storage = { dbs: { Find: async (entity: string) => entity === 'UserReceivingAddress'
        ? [{ address: 'user-address' }] : [{ tx_hash: 'recorded', output_index: 0 }] } } as unknown as Storage
    const result = await loadUtxoClassification(lnd, storage)
    for (const hash of hashes) assert.equal(result.get(`${hash}:0`)?.origin, UtxoOrigin.CHANNEL, hash)
    assert.equal(result.get('deposit:0')?.origin, UtxoOrigin.USER_DEPOSIT)
    assert.equal(result.get('recorded:0')?.origin, UtxoOrigin.USER_DEPOSIT)

    const missing = await loadUtxoClassification(lnd, storage, [
        { address: 'user-address', outpoint: OutPoint.create({ txidStr: 'new-deposit', outputIndex: 1 }) },
        { address: 'change', outpoint: OutPoint.create({ txidStr: 'open', outputIndex: 2 }) },
        { address: 'operator', outpoint: OutPoint.create({ txidStr: 'new-unknown', outputIndex: 0 }) },
    ])
    assert.deepEqual(missing.get('new-deposit:1'), { origin: UtxoOrigin.USER_DEPOSIT, is_change: false })
    assert.deepEqual(missing.get('open:2'), { origin: UtxoOrigin.CHANNEL, is_change: true })
    assert.deepEqual(missing.get('new-unknown:0'), { origin: UtxoOrigin.UNKNOWN, is_change: false })

    // Rebuilding after a history change must not retain an obsolete label.
    lnd.ListChannels = async () => ({ channels: [] })
    assert.equal((await loadUtxoClassification(lnd, storage)).get('open:0')?.origin, UtxoOrigin.UNKNOWN)
}

import { nip19 } from "@shocknet/clink-sdk"
import { getLogger, PubLogger } from "../helpers/logger.js"
import PaymentManager from "../main/paymentManager.js"
import Storage from '../storage/index.js'
import { Utils } from '../helpers/utilsWrapper.js'
import {Application} from '../storage/entity/Application.js'
import { UnsignedEvent } from "nostr-tools"
import { CLINK_BEACON_D_TAG, CLINK_BEACON_KIND, CLINK_SUPPORTED_KINDS, CLINK_VERSION } from "./clinkConstants.js"
import { LEGACY_BEACON_D_TAG } from "./clinkConstants.js"
import * as Types from '../../../proto/autogenerated/ts/types.js'
import SettingsManager from "../main/settingsManager.js"

export type ClinkBeaconContent = {
    name?: string
    avatarUrl?: string
    website?: string
    description?: string
    relays?: string[]
    fees?: { serviceFeeFloor: number, serviceFeeBps: number }
    enroll_difficulty?: number
    supported_kinds?: number[]
}


export class BeaconManager {
    serviceBeaconInterval: NodeJS.Timeout | null = null
    paymentManager: PaymentManager
    storage: Storage
    utils: Utils
    settings: SettingsManager
    log: PubLogger = getLogger({ component: "BeaconManager" })
    constructor(paymentManager: PaymentManager, storage: Storage, utils: Utils, settings: SettingsManager) {
        this.paymentManager = paymentManager
        this.storage = storage
        this.utils = utils
        this.settings = settings
    }

    async StartBeacons() {
        this.serviceBeaconInterval = setInterval(async () => {
            try {
                const fees = this.paymentManager.GetFees()
                const apps = await this.storage.applicationStorage.GetApplications()
                apps.forEach(app => {
                    this.UpdateBeacon(app, { type: 'service', name: app.name, avatarUrl: app.avatar_url, fees })
                })
            } catch (e) {
                this.log("error in beacon", (e as any).message)
            }
        }, 60 * 1000)
    }

    Stop() {
        if (this.serviceBeaconInterval) {
            clearInterval(this.serviceBeaconInterval)
        }
    }

    async UpdateBeacon(app: Application, content: Types.BeaconData) {
        if (!app.nostr_public_key) {
            getLogger({ appName: app.name })("cannot update beacon, public key not set")
            return
        }
        const sender = { type: 'app' as const, appId: app.app_id }
        this.utils.nostrSender.Send(sender, { type: 'event', event: buildLegacyBeaconEvent(app.nostr_public_key, content) })

        const nostr = this.settings.getSettings().nostrRelaySettings
        const clinkContent = buildClinkBeaconContent({
            app,
            relays: nostr.relays,
            fees: content.fees || this.paymentManager.GetFees(),
            enrollPowBits: nostr.enrollPowBits,
            website: nostr.beaconWebsite,
            description: nostr.beaconDescription,
        })
        const operatorHex = operatorPubkeyHex(nostr.operatorNpub)
        this.utils.nostrSender.Send(sender, {
            type: 'event',
            event: buildClinkBeaconEvent(app.nostr_public_key, clinkContent, operatorHex),
        })
    }
}

export const operatorPubkeyHex = (npubOrHex: string): string | undefined => {
    if (!npubOrHex) {
        return undefined
    }
    if (/^[0-9a-f]{64}$/i.test(npubOrHex)) {
        return npubOrHex.toLowerCase()
    }
    try {
        const decoded = nip19.decode(npubOrHex)
        if (decoded.type === "npub" && typeof decoded.data === "string") {
            return decoded.data.toLowerCase()
        }
    } catch {
        return undefined
    }
    return undefined
}

export const buildLegacyBeaconEvent = (pubkey: string, content: Types.BeaconData): UnsignedEvent => {
    return {
        content: JSON.stringify(content),
        created_at: Math.floor(Date.now() / 1000),
        kind: CLINK_BEACON_KIND,
        pubkey,
        tags: [["d", LEGACY_BEACON_D_TAG]],
    }
}

export const buildClinkBeaconContent = (args: {
    app: Application
    relays: string[]
    fees: Types.CumulativeFees
    enrollPowBits: number
    website?: string
    description?: string
}): ClinkBeaconContent => {
    const content: ClinkBeaconContent = {
        name: args.app.name,
        relays: args.relays,
        fees: {
            serviceFeeFloor: args.fees.serviceFeeFloor,
            serviceFeeBps: args.fees.serviceFeeBps,
        },
        supported_kinds: [...CLINK_SUPPORTED_KINDS],
    }
    const website = args.website?.trim()
    const description = args.description?.trim()
    if (args.app.avatar_url) {
        content.avatarUrl = args.app.avatar_url
    }
    if (website) {
        content.website = website
    }
    if (description) {
        content.description = description
    }
    if (args.enrollPowBits > 0) {
        content.enroll_difficulty = args.enrollPowBits
    }
    return content
}

export const buildClinkBeaconEvent = (pubkey: string, content: ClinkBeaconContent, operatorHex?: string): UnsignedEvent => {
    const tags: string[][] = [
        ["d", CLINK_BEACON_D_TAG],
        ["clink_version", CLINK_VERSION],
    ]
    if (operatorHex) {
        tags.push(["operator", operatorHex])
    }
    return {
        content: JSON.stringify(content),
        created_at: Math.floor(Date.now() / 1000),
        kind: CLINK_BEACON_KIND,
        pubkey,
        tags,
    }
}
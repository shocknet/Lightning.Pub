export const gfy6Reason = {
    k1AlreadyProcessed: 'k1_already_processed',
    invoiceInProgress: 'invoice_in_progress',
    invoiceAlreadyFailed: 'invoice_already_failed',
    invoiceAlreadyPaid: 'invoice_already_paid',
} as const
export type Gfy6Reason = typeof gfy6Reason[keyof typeof gfy6Reason]

export type NdebitFailureWithExtras = NdebitFailure & {
    range?: { min: number, max: number }
    reason?: Gfy6Reason
    retry_after?: number
}

export type ClinkDebitResponse = NdebitSuccess

export type NdebitErrorOpts = { max?: number, reason?: Gfy6Reason, retry_after?: number }

export class NdebitError extends ClinkError {
    opts: NdebitErrorOpts | undefined
    constructor(args: { code: number, message?: string, opts?: NdebitErrorOpts }) {
        const { code, message, opts } = args
        super(message || codeToMessage(code), code)
        this.opts = opts
    }
    getPayload = (): NdebitFailureWithExtras => {
        const payload: NdebitFailureWithExtras = {
            res: "GFY",
            code: this.code,
            error: this.message,
        }
        if (this.code === 5 && this.opts?.max !== undefined) {
            payload.range = { min: 1, max: this.opts.max }
        }
        if (this.opts?.reason) {
            payload.reason = this.opts.reason
        }
        if (this.opts?.retry_after !== undefined) {
            payload.retry_after = this.opts.retry_after
        }
        return payload
    }
}

export const validateDebitReq = (req: unknown): NdebitData => {
    try {
        return validateNdebitData(req)
    } catch (e: any) {
        throw new NdebitError({ code: 6, message: `${codeToMessage(6)}: ${e?.message || "malformed request"}` })
    }
}


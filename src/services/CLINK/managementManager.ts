import { UserOffer } from "../storage/entity/UserOffer.js";
import Storage from "../storage/index.js";
import * as Types from "../../../proto/autogenerated/ts/types.js";
import { nofferEncode, OfferPointer, OfferPriceType, NmanageRequest, NmanageSuccess, NmanageCreateOffer, NmanageUpdateOffer, NmanageDeleteOffer, NmanageGetOffer, NmanageListOffers, OfferData, OfferFields } from "@shocknet/clink-sdk";
import { getLogger, PubLogger, ERROR } from "../helpers/logger.js";
import SettingsManager from "../main/settingsManager.js";
import { assertCallbackUrlAllowed, SafeOutboundFetchError } from "../helpers/safeOutboundFetch.js";
import { assertValidOfferPriceSats } from "../helpers/offerValidation.js";
import { isAccountOwner, denyStrangerLiveAuth } from "./clinkOwner.js";
import { ClinkCtx, ClinkError, encodeClinkResponse } from "./clinkTypes.js";
import { CLINK_MANAGE_KIND } from "./clinkConstants.js";
import { NotificationsManager } from "../main/notificationsManager.js";
import { BackupManager } from "../backup/backupManager.js";
import { Application } from "../storage/entity/Application.js";
import { ApplicationUser } from "../storage/entity/ApplicationUser.js";
import { NmanageError } from "./manageTypes.js";
import { CLINK_AUTH_TTL_MS, ClinkRateLimiter } from "./clinkRateLimit.js";

class ManageAuthRequired extends Error {
    constructor() {
        super("manage auth required")
    }
}

type PendingManage = { request: NmanageRequest, ctx: ClinkCtx }

export class ManagementManager {
    private storage: Storage;
    private settings: SettingsManager;
    private pendingRequests = new ClinkRateLimiter<PendingManage>({ windowMs: CLINK_AUTH_TTL_MS, maxHits: 1 })
    private logger: PubLogger
    notificationsManager: NotificationsManager
    private backupManager: BackupManager
    constructor(storage: Storage, settings: SettingsManager, notificationsManager: NotificationsManager, backupManager: BackupManager) {
        this.storage = storage;
        this.settings = settings;
        this.notificationsManager = notificationsManager
        this.backupManager = backupManager
        this.logger = getLogger({ component: 'ManagementManager' })
    }

    ResetManage = async (ctx: Types.UserContext, req: Types.ManageOperation): Promise<void> => {
        await this.storage.managementStorage.removeGrant(ctx.app_user_id, req.npub)
        this.backupManager.notifyBackupTable('management_grants')
    }

    AuthorizeManage = async (ctx: Types.UserContext, req: Types.ManageAuthorizationRequest): Promise<Types.ManageAuthorization> => {
        const grant = await this.storage.managementStorage.addGrant(ctx.app_user_id, req.authorize_npub, req.ban)
        this.backupManager.notifyBackupTable('management_grants')
        const awaiting = this.pendingRequests.take(req.authorize_npub)
        if (awaiting) {
            if (grant.banned) {
                this.sendManage(awaiting.ctx, new NmanageError({ code: 1, message: 'Request Denied: App is banned' }).getPayload())
            } else {
                await this.replyToAwaiting(awaiting)
            }
        }
        return {
            manage_id: grant.serial_id.toString(),
            authorized: !grant.banned,
            npub: grant.app_pubkey,
        }
    }

    GetManageAuthorizations = async (ctx: Types.UserContext): Promise<Types.ManageAuthorizations> => {
        const grants = await this.storage.managementStorage.getGrants(ctx.app_user_id)
        return {
            manages: grants.map(grant => ({
                manage_id: grant.serial_id.toString(),
                authorized: !grant.banned,
                npub: grant.app_pubkey,
            }))
        }
    }

    private sendManage(ctx: ClinkCtx, body: unknown) {
        const event = encodeClinkResponse(CLINK_MANAGE_KIND, body, { pub: ctx.pub, id: ctx.eventId })
        this.storage.NostrSender().Send({ type: 'app', appId: ctx.appId }, { type: 'event', event, encrypt: { toPub: ctx.pub } })
    }

    private async replyToAwaiting(awaiting: PendingManage) {
        try {
            const result = await this.HandleClinkManage(awaiting.ctx, awaiting.request)
            if (result) {
                this.sendManage(awaiting.ctx, result)
            }
        } catch (err: any) {
            this.logger(ERROR, err.message || err)
            if (err instanceof ClinkError) {
                this.sendManage(awaiting.ctx, err.getPayload())
            } else {
                this.sendManage(awaiting.ctx, { res: 'GFY', code: 2, error: 'Temporary Failure' })
            }
        }
    }

    private sendManageAuthorizationRequest = async (app: Application, appUser: ApplicationUser, { requestId, npub }: { requestId: string, npub: string }) => {
        const userPub = appUser.nostr_public_key!
        const liveManageRequest: Types.LiveManageRequest = { npub: npub, request_id: requestId }
        const message: Types.LiveManageRequest & { requestId: string, status: 'OK' } = { requestId: "GetLiveManageRequests", status: 'OK', ...liveManageRequest }
        this.logger("Sending manage authorization request to", npub, "for app", app.app_id)
        this.storage.NostrSender().Send({ type: 'app', appId: app.app_id }, { type: 'content', content: JSON.stringify(message), pub: userPub })

        await this.notificationsManager.SendEncryptedPayload(app, appUser, {
            data: {
                type: Types.PushNotificationPayload_data_type.MANAGE_AUTH_REQ,
                manage_auth_req: liveManageRequest
            }
        }, {
            title: "Manage request",
            body: "You have a new manage authorization request"
        })
    }

    private async handleAuthRequired(nmanageReq: NmanageRequest, ctx: ClinkCtx) {
        const appUserId = (nmanageReq as { pointer?: string }).pointer
        if (!appUserId) {
            this.logger("No pointer provided", ctx.pub)
            throw new NmanageError({ code: 1, message: 'Request Denied: No pointer provided, cannot sent auth request' })
        }
        const app = await this.storage.applicationStorage.GetApplication(ctx.appId)
        const appUser = await this.storage.applicationStorage.GetApplicationUser(app, appUserId)
        if (!appUser.nostr_public_key) {
            this.logger("App user has no nostr public key", ctx.pub)
            throw new NmanageError({ code: 1, message: 'Request Denied: App user has no nostr public key' })
        }
        const added = this.pendingRequests.tryAdd(ctx.pub, { request: nmanageReq, ctx })
        if (!added.ok) {
            throw new NmanageError({ code: 4, message: 'Rate Limited', opts: { retry_after: added.retryAfterUnix } })
        }
        try {
            await this.sendManageAuthorizationRequest(app, appUser, { requestId: ctx.eventId, npub: ctx.pub })
        } catch (err) {
            this.pendingRequests.take(ctx.pub)
            throw err
        }
    }

    async HandleClinkManage(ctx: ClinkCtx, nmanageReq: NmanageRequest): Promise<NmanageSuccess | null> {
        try {
            return await this.doNmanage(nmanageReq, ctx)
        } catch (err) {
            if (err instanceof ManageAuthRequired) {
                await this.handleAuthRequired(nmanageReq, ctx)
                return null
            }
            throw err
        }
    }

    private async doNmanage(nmanageReq: NmanageRequest, ctx: ClinkCtx): Promise<NmanageSuccess> {
        const action = nmanageReq.action
        switch (action) {
            case "create":
                return this.toManageSuccess(ctx.appId, await this.createOffer(nmanageReq, ctx.pub, ctx.appId))
            case "update":
                return this.toManageSuccess(ctx.appId, await this.updateOffer(nmanageReq, ctx.pub, ctx.appId))
            case "delete":
                await this.deleteOffer(nmanageReq, ctx.pub, ctx.appId)
                return this.toManageSuccess(ctx.appId, undefined)
            case "get":
                return this.toManageSuccess(ctx.appId, await this.getOffer(nmanageReq, ctx.pub, ctx.appId))
            case "list":
                return this.toManageSuccess(ctx.appId, await this.listOffers(nmanageReq, ctx.pub, ctx.appId))
            default:
                throw new NmanageError({ code: 1, message: `Request Denied: Unknown action: ${action}` })
        }
    }

    private getOfferData(offer: UserOffer, appPub: string): OfferData {
        const pointer: OfferPointer = {
            offer: offer.offer_id,
            pubkey: appPub,
            relay: this.settings.getSettings().nostrRelaySettings.relays[0],
            priceType: offer.price_sats > 0 ? OfferPriceType.Fixed : OfferPriceType.Spontaneous,
            price: offer.price_sats,
        }
        return {
            id: offer.offer_id,
            label: offer.label,
            price_sats: offer.price_sats,
            callback_url: offer.callback_url,
            payer_data: offer.payer_data || [],
            noffer: nofferEncode(pointer),
        }
    }

    private async toManageSuccess(appId: string, args: UserOffer | UserOffer[] | undefined): Promise<NmanageSuccess> {
        const app = await this.storage.applicationStorage.GetApplication(appId)
        if (args && Array.isArray(args)) {
            return {
                res: 'ok', resource: 'offer', details: args.map(offer => this.getOfferData(offer, app.nostr_public_key!))
            }
        }
        if (!args) {
            return { res: 'ok', resource: 'offer' }
        }
        return {
            res: 'ok', resource: 'offer', details: this.getOfferData(args, app.nostr_public_key!)
        }
    }

    private async getOffer(nmanageReq: NmanageGetOffer, requestorPub: string, appId: string): Promise<UserOffer> {
        return this.validateOfferAccess(nmanageReq.offer.id, requestorPub, appId)
    }

    private async listOffers(nmanageReq: NmanageListOffers, requestorPub: string, appId: string): Promise<UserOffer[]> {
        const appUserId = nmanageReq.pointer
        if (!appUserId) {
            throw new NmanageError({ code: 1, message: 'Request Denied: No pointer provided' })
        }
        await this.validateGrantAccess(appUserId, requestorPub, appId)
        if (await this.isPointerOwner(appId, appUserId, requestorPub)) {
            return this.storage.offerStorage.GetUserOffers(appUserId)
        }
        return this.storage.offerStorage.getManagedUserOffers(appUserId, requestorPub)
    }

    private validateOfferFields(fields: OfferFields) {
        if (!fields.label || typeof fields.label !== 'string') {
            throw new NmanageError({ code: 5, message: 'Invalid Field/Value', opts: { field: 'label' } })
        }
        if (fields.price_sats !== undefined && fields.price_sats !== null) {
            if (typeof fields.price_sats !== 'number') {
                throw new NmanageError({ code: 5, message: 'Invalid Field/Value', opts: { field: 'price_sats' } })
            }
            try {
                assertValidOfferPriceSats(fields.price_sats)
            } catch {
                throw new NmanageError({ code: 5, message: 'Invalid Field/Value', opts: { field: 'price_sats' } })
            }
        }
        if (fields.callback_url && typeof fields.callback_url !== 'string') {
            throw new NmanageError({ code: 5, message: 'Invalid Field/Value', opts: { field: 'callback_url' } })
        }
        if (fields.callback_url) {
            try {
                assertCallbackUrlAllowed(fields.callback_url)
            } catch (err) {
                const message = err instanceof SafeOutboundFetchError ? err.message : 'callback url is invalid'
                throw new NmanageError({ code: 5, message, opts: { field: 'callback_url' } })
            }
        }
        if (fields.payer_data && !Array.isArray(fields.payer_data)) {
            throw new NmanageError({ code: 5, message: 'Invalid Field/Value', opts: { field: 'payer_data' } })
        }
    }

    private async createOffer(nmanageReq: NmanageCreateOffer, requestorPub: string, appId: string): Promise<UserOffer> {
        const appUserId = nmanageReq.pointer
        if (!appUserId) {
            throw new NmanageError({ code: 1, message: 'Request Denied: No pointer provided' })
        }
        await this.validateGrantAccess(appUserId, requestorPub, appId)
        this.validateOfferFields(nmanageReq.offer.fields)
        const offer = await this.storage.offerStorage.AddUserOffer(appUserId, {
            label: nmanageReq.offer.fields.label,
            callback_url: nmanageReq.offer.fields.callback_url,
            price_sats: nmanageReq.offer.fields.price_sats,
            payer_data: nmanageReq.offer.fields.payer_data,
            management_pubkey: requestorPub,
        })
        this.backupManager.notifyBackupTable('user_offers')
        return offer
    }

    private async isPointerOwner(appId: string, appUserId: string, requestorPub: string): Promise<boolean> {
        try {
            const app = await this.storage.applicationStorage.GetApplication(appId)
            const appUser = await this.storage.applicationStorage.GetApplicationUser(app, appUserId)
            return isAccountOwner(appUser, requestorPub)
        } catch {
            return false
        }
    }

    private async validateGrantAccess(appUserId: string, requestorPub: string, appId: string): Promise<void> {
        try {
            const app = await this.storage.applicationStorage.GetApplication(appId)
            const appUser = await this.storage.applicationStorage.GetApplicationUser(app, appUserId)
            if (isAccountOwner(appUser, requestorPub)) {
                return
            }
            const grant = await this.storage.managementStorage.getGrant(appUserId, requestorPub)
            if (!grant) {
                if (denyStrangerLiveAuth(appUser)) {
                    throw new NmanageError({ code: 1, message: 'Request Denied' })
                }
                this.logger("No grant found", appUserId, requestorPub)
                throw new ManageAuthRequired()
            }
            if (grant.expires_at_unix > 0 && grant.expires_at_unix < Math.floor(Date.now() / 1000)) {
                this.logger("Grant expired", appUserId, requestorPub)
                if (denyStrangerLiveAuth(appUser)) {
                    throw new NmanageError({ code: 1, message: 'Request Denied' })
                }
                throw new ManageAuthRequired()
            }
            if (grant.banned) {
                throw new NmanageError({ code: 1, message: 'Request Denied: App is banned' })
            }
        } catch (err) {
            if (err instanceof NmanageError || err instanceof ManageAuthRequired) {
                throw err
            }
            throw new NmanageError({ code: 1, message: 'Request Denied' })
        }
    }

    private async validateOfferAccess(offerId: string, requestorPub: string, appId: string): Promise<UserOffer> {
        const offer = await this.storage.offerStorage.GetOffer(offerId)
        if (!offer) {
            throw new NmanageError({ code: 1, message: 'Request Denied: Offer not found' })
        }
        if (await this.isPointerOwner(appId, offer.app_user_id, requestorPub)) {
            return offer
        }
        if (offer.management_pubkey !== requestorPub) {
            throw new NmanageError({ code: 1, message: 'Request Denied: App not authorized to update offer' })
        }
        await this.validateGrantAccess(offer.app_user_id, requestorPub, appId)
        return offer
    }

    private async updateOffer(nmanageReq: NmanageUpdateOffer, requestorPub: string, appId: string): Promise<UserOffer> {
        const offer = await this.validateOfferAccess(nmanageReq.offer.id, requestorPub, appId)
        this.validateOfferFields(nmanageReq.offer.fields)
        for (const data of nmanageReq.offer.fields.payer_data || []) {
            if (typeof data !== 'string') {
                throw new NmanageError({ code: 5, message: 'Invalid Field/Value', opts: { field: 'payer_data' } })
            }
        }
        await this.storage.offerStorage.UpdateUserOffer(offer.app_user_id, nmanageReq.offer.id, {
            label: nmanageReq.offer.fields.label,
            callback_url: nmanageReq.offer.fields.callback_url,
            price_sats: nmanageReq.offer.fields.price_sats,
            payer_data: nmanageReq.offer.fields.payer_data,
        })
        this.backupManager.notifyBackupTable('user_offers')
        const updatedOffer = await this.storage.offerStorage.GetOffer(nmanageReq.offer.id)
        if (!updatedOffer) {
            throw new NmanageError({ code: 2, message: 'Temporary Failure: Offer not found' })
        }
        return updatedOffer
    }

    private async deleteOffer(nmanageReq: NmanageDeleteOffer, requestorPub: string, appId: string): Promise<void> {
        const offer = await this.validateOfferAccess(nmanageReq.offer.id, requestorPub, appId)
        await this.storage.offerStorage.DeleteUserOffer(offer.app_user_id, offer.offer_id)
        this.backupManager.notifyBackupTable('user_offers')
    }
}

import { nip19 } from 'nostr-tools'
import { getLogger } from "../helpers/logger.js"
import NewWizardServer from "../../../proto/wizard_service/autogenerated/ts/express_server.js"
import * as WizardTypes from "../../../proto/wizard_service/autogenerated/ts/types.js"
import SettingsManager from "../main/settingsManager.js"
import Storage from '../storage/index.js'
import { Unlocker } from "../main/unlocker.js"
import { AdminManager } from '../main/adminManager.js';
import { assertRemoteBackup, DEFAULT_SFTP_PORT, pickDefaultApp, remoteBackupFromSettings, wizardFirstRun } from '../main/adminNodeSettings.js'
import { RestoreManager } from '../backup/restoreManager.js'
import { applyWizardDefaultApp } from './defaultApp.js'
import { registerAvatarUploadRoute } from './avatarUploadRoute.js'
const { nprofileEncode } = nip19
const defaultProviderPub = ""
export class Wizard {
    log = getLogger({ component: "wizard" })
    settings: SettingsManager
    adminManager: AdminManager
    restoreManager: RestoreManager
    storage: Storage
    configQueue: { res: (reload: boolean) => void }[] = []
    awaitingNprofile: { res: (nprofile: string) => void }[] = []
    nprofile = ""
    relays: string[] = []
    constructor(settings: SettingsManager, storage: Storage, adminManager: AdminManager, restoreManager: RestoreManager, private unlocker: Unlocker) {
        this.settings = settings
        this.adminManager = adminManager
        this.storage = storage
        this.restoreManager = restoreManager
        this.log('Starting wizard...')
        // No login. This UI is for Start9 and Umbrel, which publish it only on the
        // appliance network (Start9: LAN-only, port 1777). Pub listens on every
        // interface; the appliance keeps the port off the public internet.
        // A missing wizard password is not a bug.
        const wizardServer = NewWizardServer({
            WizardState: async () => { return this.WizardState() },
            WizardConfig: async ({ req }) => { return this.wizardConfig(req) },
            GetAdminConnectInfo: async () => { return this.GetAdminConnectInfo() },
            GetServiceState: async () => { return this.GetServiceState() },
            WizardRestore: async ({ req }) => { return this.WizardRestore(req) }
        }, {
            GuestAuthGuard: async () => "",
            metricsCallback: () => { },
            staticFiles: 'static',
            configureApp: (app) => registerAvatarUploadRoute(app, () => this.nodeAvatarKey()),
        })
        wizardServer.Listen(settings.getSettings().serviceSettings.servicePort + 1)
    }

    nodeAvatarKey = async (): Promise<Uint8Array> => {
        const apps = await this.storage.applicationStorage.GetApplications()
        const app = pickDefaultApp(apps, this.settings.getSettings().serviceSettings.defaultAppName) || apps[0]
        const hex = app?.nostr_private_key || ""
        if (!/^[0-9a-fA-F]{64}$/.test(hex)) {
            throw new Error("This node cannot sign an upload yet")
        }
        return Buffer.from(hex, "hex")
    }

    GetServiceState = async (): Promise<WizardTypes.ServiceStateResponse> => {
        // Keep this even if the rest of the snapshot fails: the welcome page needs it to
        // show Retry Restore after a committed restore (is_db_clean is then false).
        // first_run is independent of is_db_clean: non-blocking startup creates a default
        // app before the operator submits config.
        const hasOngoingRecovery = this.restoreManager.IsRecoveryActive()
        const firstRun = (dbClean: boolean) => {
            try {
                const service = this.settings.getSettings().serviceSettings
                return wizardFirstRun({
                    hasOngoingRecovery,
                    wizardConfigured: service.wizardConfigured,
                    dbClean,
                    wizardNonBlocking: service.wizardNonBlocking,
                })
            } catch {
                return false
            }
        }
        // Hoisted so a later failure still reports first run once cleanliness is known.
        let dbClean = false
        try {
            const apps = await this.storage.applicationStorage.GetApplications()
            const appNamesList = apps.map(app => app.name).join(', ')
            const relays = this.settings.getSettings().nostrRelaySettings.relays
            const relayUrl = (relays && relays.length > 0) ? relays[0] : '';
            const defaultApp = pickDefaultApp(apps, this.settings.getSettings().serviceSettings.defaultAppName) || apps[0]
            dbClean = await this.storage.IsDbClean()
            // Determine LND state and watchdog
            let lndState: WizardTypes.LndState = WizardTypes.LndState.OFFLINE
            let watchdogOk = false
            try {
                const info = await this.adminManager.LndGetInfo()
                const online = info.synced_to_chain && info.synced_to_graph
                lndState = online ? WizardTypes.LndState.ONLINE : WizardTypes.LndState.SYNCING
                watchdogOk = !info.watchdog_barking
            } catch {
                lndState = WizardTypes.LndState.OFFLINE
                watchdogOk = false
            }
            return {
                admin_npub: this.adminManager.GetAdminNpub(),
                http_url: this.settings.getSettings().serviceSettings.serviceUrl,
                lnd_state: lndState,
                nprofile: this.nprofileForRelays(relays),
                provider_name: defaultApp?.name || appNamesList,
                relay_connected: this.adminManager.GetNostrConnected(),
                relays,
                watchdog_ok: watchdogOk,
                source_name: defaultApp?.name || this.settings.getSettings().serviceSettings.defaultAppName || appNamesList,
                relay_url: relayUrl,
                automate_liquidity: !this.settings.getSettings().liquiditySettings.disableLiquidityProvider,
                remote_backup: remoteBackupFromSettings(this.settings.getSettings().backupSettings),
                avatar_url: defaultApp?.avatar_url || '',
                app_id: defaultApp?.app_id || '',
                has_seed: await this.unlocker.HasSeedForNode(),
                is_db_clean: dbClean,
                first_run: firstRun(dbClean),
                has_ongoing_recovery: hasOngoingRecovery,
            }
        } catch (e) {
            this.log(`Error in GetServiceState: ${(e as Error).message}`)
            // Return a default/error state that is still valid JSON to prevent client-side parse errors
            return {
                admin_npub: '',
                http_url: '',
                lnd_state: WizardTypes.LndState.OFFLINE,
                nprofile: '',
                provider_name: 'Error loading state',
                relay_connected: false,
                relays: [],
                watchdog_ok: false,
                source_name: 'Error',
                relay_url: '',
                automate_liquidity: false,
                remote_backup: { enabled: false, host: '', port: DEFAULT_SFTP_PORT, user: '', pass: '', host_fingerprint: '' },
                avatar_url: '',
                app_id: '',
                has_seed: false,
                is_db_clean: dbClean,
                first_run: firstRun(dbClean),
                has_ongoing_recovery: hasOngoingRecovery,
            }
        }
    }


    WizardState = async (): Promise<WizardTypes.StateResponse> => {
        return {
            config_sent: false,
            admin_linked: this.adminManager.GetAdminNpub() !== "",
        }
    }
    IsInitialized = () => {
        return !!this.adminManager.GetAdminNpub()
    }

    GetAdminConnectInfo = async (): Promise<WizardTypes.AdminConnectInfoResponse> => {
        await this.getNprofile()
        const nprofile = this.nprofileForRelays()
        const enrolledAdmin = this.adminManager.GetAdminNpub()
        if (enrolledAdmin !== "") {
            return {
                nprofile, connect_info: {
                    type: WizardTypes.AdminConnectInfoResponse_connect_info_type.ENROLLED_NPUB,
                    enrolled_npub: enrolledAdmin
                }
            }
        }
        const adminEnroll = this.adminManager.ReadAdminEnrollToken()
        if (adminEnroll !== "") {
            return {
                nprofile, connect_info: {
                    type: WizardTypes.AdminConnectInfoResponse_connect_info_type.ADMIN_TOKEN,
                    admin_token: adminEnroll
                }
            }
        }
        throw new Error("something went wrong initializing admin creds")
    }

    getNprofile = async (): Promise<string> => {
        if (this.nprofile !== "") {
            return this.nprofile
        }
        this.log("waiting for nprofile")
        // Add timeout to prevent hanging forever
        return Promise.race([
            new Promise<string>((res) => {
                this.awaitingNprofile.push({ res })
            }),
            new Promise<string>((_, reject) => {
                setTimeout(() => reject(new Error("timeout waiting for nprofile")), 30000)
            })
        ])
    }

    AddConnectInfo = (nprofile: string, relays: string[]) => {
        this.nprofile = nprofile
        this.relays = relays
        this.awaitingNprofile.forEach(q => q.res(nprofile))
        this.awaitingNprofile = []
    }

    private nprofileForRelays = (relays = this.settings.getSettings().nostrRelaySettings.relays): string => {
        if (!this.nprofile) {
            return ''
        }
        try {
            const decoded = nip19.decode(this.nprofile)
            if (decoded.type === 'nprofile' && decoded.data.pubkey) {
                const next = nprofileEncode({ pubkey: decoded.data.pubkey, relays })
                this.nprofile = next
                this.relays = relays
                return next
            }
        } catch (e) {
            this.log(`failed to encode nprofile with current relays: ${(e as Error).message}`)
        }
        return this.nprofile
    }

    Configure = async (): Promise<boolean> => {
        if (this.IsInitialized()) {
            return false
        }
        return new Promise((res) => {
            this.configQueue.push({ res })
        })
    }

    wizardConfig = async (req: WizardTypes.ConfigRequest): Promise<void> => {
        if (this.restoreManager.IsRecoveryActive()) {
            throw new Error('Recovery in progress. Finish or abandon the restore before configuring the node.')
        }
        const err = WizardTypes.ConfigRequestValidate(req, {
            source_name_CustomCheck: source => source !== '',
            relay_url_CustomCheck: relay => relay !== '',
        })
        if (err != null) { throw new Error(err.message) }
        assertRemoteBackup(req.remote_backup)

        const has_seed = await this.unlocker.HasSeedForNode()
        if (!has_seed && req.remote_backup.enabled) {
            this.log("Ignoring request to enable remote backup because no seed is available")
            req.remote_backup = { ...req.remote_backup, enabled: false }
        }

        const pendingConfig = { sourceName: req.source_name, relayUrl: req.relay_url, automateLiquidity: req.automate_liquidity }

        // Rename through the admin transaction so a collision cannot leave DEFAULT_APP_NAME
        // pointing at a different existing app. Other settings come after so they stay put if rename fails.
        const nameUpdated = await applyWizardDefaultApp(
            this.adminManager,
            this.settings,
            this.storage,
            pendingConfig.sourceName,
            req.avatar_url,
        )
        // automateLiquidity=true means enable automation, so disableLiquidityProvider should be false
        await this.settings.updateDisableLiquidityProvider(!pendingConfig.automateLiquidity)
        this.adminManager.liquidityProvider?.syncAfterSettingsChange()
        await this.settings.updateRemoteBackup(req.remote_backup)
        await this.settings.markWizardConfigured()

        const relayUpdated = await this.settings.updateRelayUrl(pendingConfig.relayUrl)
        if (relayUpdated) {
            await this.adminManager.ResetNostr()
            this.nprofileForRelays([pendingConfig.relayUrl])
        }

        // If already initialized, treat as idempotent update for env and exit
        if (this.IsInitialized()) {
            this.log("reloaded wizard config")
            if (nameUpdated) this.log("name updated")
            if (relayUpdated) this.log("relay updated")
            return
        }

        // First-time configuration flow
        this.configQueue.forEach(q => q.res(true))
        this.configQueue = []
        return
    }

    WizardRestore = async (req: WizardTypes.RestoreRequest): Promise<WizardTypes.RestoreResponse> => {
        const err = WizardTypes.RestoreRequestValidate(req, {
            phrase_CustomCheck: phrase => phrase !== '',
            source_Options: {
                ftp_host_Options: {
                    host_CustomCheck: host => host.trim() !== '' && !/\s/.test(host.trim()),
                    port_CustomCheck: port => Number.isSafeInteger(port) && port >= 0 && port <= 65535,
                },
            },
        })
        if (err != null) throw new Error(err.message)
        return this.restoreManager.RestoreFromSource(req)
    }
}
import type LND from '../lnd/lnd.js'
import type Storage from '../storage/index.js'
import type { UserReceivingAddress } from '../storage/entity/UserReceivingAddress.js'
import type { AddressReceivingTransaction } from '../storage/entity/AddressReceivingTransaction.js'
import { classifyUtxos } from '../helpers/utxoOrigin.js'
import { UtxoOrigin } from '../../../proto/autogenerated/ts/types.js'
import type { Utxo } from '../../../proto/lnd/lightning.js'

/** Lazy historical backfill on first dashboard request; no address changes or
 * database migration required. Refreshed periodically by AdminManager.
 */
export async function loadUtxoClassification(lnd: LND, storage: Storage, utxos: Pick<Utxo, 'address' | 'outpoint'>[] = []) {
    const [history, open, closed, pending, sweeps, addresses, users, deposits] = await Promise.all([
        lnd.GetTransactions(0),
        lnd.ListChannels(),
        lnd.ListClosedChannels(),
        lnd.ListPendingChannels(),
        lnd.ListSweeps(),
        lnd.ListAddresses(),
        storage.dbs.Find<UserReceivingAddress>('UserReceivingAddress', {}),
        storage.dbs.Find<AddressReceivingTransaction>('AddressReceivingTransaction', { where: { internal: false } }),
    ])
    const channelTxids = new Set(sweeps)
    const funding = (point?: string) => { if (point) channelTxids.add(point.split(':')[0]) }
    const closing = (hash?: string) => { if (hash) channelTxids.add(hash) }
    open.channels.forEach(channel => funding(channel.channelPoint))
    closed.channels.forEach(channel => {
        funding(channel.channelPoint)
        closing(channel.closingTxHash)
        // Resolution sweeps cover historical force closes even when intermediate
        // transactions are absent from the wallet's transaction history.
        channel.resolutions.forEach(resolution => closing(resolution.sweepTxid))
    })
    pending.pendingOpenChannels.forEach(channel => funding(channel.channel?.channelPoint))
    for (const channel of [...pending.pendingClosingChannels, ...pending.pendingForceClosingChannels, ...pending.waitingCloseChannels]) {
        funding(channel.channel?.channelPoint)
        closing(channel.closingTxid)
    }
    const userAddresses = new Set(users.map(user => user.address))
    const userOutpoints = new Set(deposits.map(deposit => `${deposit.tx_hash}:${deposit.output_index}`))
    const changeAddresses = new Set(addresses.filter(address => address.change).map(address => address.address))
    const result = classifyUtxos(
        history.transactions,
        userAddresses,
        userOutpoints,
        channelTxids,
        changeAddresses,
    )
    // ListUnspent and history aren't atomic. Direct evidence still classifies a
    // coin whose transaction is absent from the history snapshot.
    for (const utxo of utxos) {
        if (!utxo.outpoint) continue
        const point = `${utxo.outpoint.txidStr}:${utxo.outpoint.outputIndex}`
        if (!result.has(point)) result.set(point, {
            origin: userOutpoints.has(point) || userAddresses.has(utxo.address) ? UtxoOrigin.USER_DEPOSIT
                : channelTxids.has(utxo.outpoint.txidStr) ? UtxoOrigin.CHANNEL : UtxoOrigin.UNKNOWN,
            is_change: changeAddresses.has(utxo.address),
        })
    }
    // The graph is only needed during reconstruction. Cache current coins rather
    // than retaining every spent historical output for the dashboard's lifetime.
    return utxos.length ? new Map(utxos.flatMap(utxo => {
        const point = `${utxo.outpoint?.txidStr}:${utxo.outpoint?.outputIndex}`
        const classification = result.get(point)
        return classification ? [[point, classification] as const] : []
    })) : result
}

import fs from 'fs'
import crypto from 'crypto'
import { GrpcTransport } from "@protobuf-ts/grpc-transport";
import { credentials, Metadata } from '@grpc/grpc-js'
import { ERROR, getLogger } from '../helpers/logger.js';
import { WalletUnlockerClient } from '../../../proto/lnd/walletunlocker.client.js';
import { InitWalletReq } from '../lnd/initWalletReq.js';
import { candidateNodePubkeys } from '../lnd/nodeKey.js';
import Storage from '../storage/index.js'
import { LightningClient } from '../../../proto/lnd/lightning.client.js';
import { ChanBackupSnapshot } from '../../../proto/lnd/lightning.js';
import { StateClient } from '../../../proto/lnd/stateservice.client.js';
import * as Types from '../../../proto/autogenerated/ts/types.js'
import SettingsManager from './settingsManager.js';
import { NostrSender } from '../nostr/sender.js';
import { nip44, UnsignedEvent } from 'nostr-tools';
import { WalletState } from '../../../proto/lnd/stateservice.js';
import { Application } from '../storage/entity/Application.js';
import { selectDefaultApp } from '../helpers/defaultAppSelector.js';
const DeadLineMetadata = (deadline = 10 * 1000) => ({ deadline: Date.now() + deadline })
type EncryptedData = { iv: string, encrypted: string }
type Seed = { plaintextSeed: string[], encryptedSeed: EncryptedData, entropy?: Buffer }
const SCB_BACKUP_KIND = 30078
const SCB_BACKUP_D_TAG = 'Lightning.Pub/backup/scb'
const BACKUP_RESUBSCRIBE_SECONDS = 30
const WALLET_STATE_WAIT_SECONDS = 300
const WALLET_STATE_QUERY_SECONDS = 10
const SYNC_PROGRESS_SECONDS = 5
const SECONDS_PER_BLOCK = 600
export type AppKeys = { nostr_private_key: string, nostr_public_key: string }
type AppWithKeys = Application & AppKeys

export class Unlocker {

    settings: SettingsManager
    storage: Storage
    abortController = new AbortController()
    subbedToBackups = false
    nodePub: string | null = null
    log = getLogger({ component: "unlocker" })
    nostrSender: NostrSender
    constructor(settings: SettingsManager, storage: Storage, nostrSender: NostrSender) {
        this.settings = settings
        this.storage = storage
        this.nostrSender = nostrSender
    }

    Stop = () => {
        this.abortController.abort()
    }

    getCreds = () => {
        const macroonPath = this.settings.getSettings().lndNodeSettings.lndMacaroonPath
        const certPath = this.settings.getSettings().lndNodeSettings.lndCertPath
        let macaroon = ""
        let lndCert: Buffer
        try {
            lndCert = fs.readFileSync(certPath)
        } catch (err: any) {
            throw new Error("failed to access lnd cert, make sure to set LND_CERT_PATH in .env, that the path is correct, and that lnd is running")
        }
        try {
            macaroon = fs.readFileSync(macroonPath).toString('hex');
        } catch (err: any) {
            if (err.code !== 'ENOENT') {
                throw err
            }
        }
        return { lndCert, macaroon }
    }

    WalletExists = async (): Promise<boolean> => {
        if (this.settings.getSettings().liquiditySettings.useOnlyLiquidityProvider) {
            return false
        }
        return (await this.getWalletState(WALLET_STATE_WAIT_SECONDS)) !== WalletState.NON_EXISTING
    }

    HasSeedForNode = async (): Promise<boolean> => {
        if (this.settings.getSettings().liquiditySettings.useOnlyLiquidityProvider) {
            return false
        }
        try {
            if (this.nodePub) {
                return !!(await this.storage.liquidityStorage.GetNoodeSeed(this.nodePub))
            }
            return (await this.getWalletState(WALLET_STATE_QUERY_SECONDS)) === WalletState.NON_EXISTING
        } catch (err: any) {
            this.log("failed to check seed for node", err.message || err)
            return false
        }
    }

    private getWalletState = (timeout: number | null) => {
        const { lndCert } = this.getCreds()
        return this.WaitWalletState(this.GetStateClient(lndCert), timeout)
    }

    Restore = async (seed: string[], recoveryWindow: number) => {
        if (this.settings.getSettings().liquiditySettings.useOnlyLiquidityProvider) {
            this.log("USE_ONLY_LIQUIDITY_PROVIDER enabled, skipping LND restore")
            throw new Error("USE_ONLY_LIQUIDITY_PROVIDER enabled, cannot restore LND")
        }
        const { lndCert } = this.getCreds()
        const state = this.GetStateClient(lndCert)
        const { adminMacaroon } = await this.initFlow(lndCert, state, { seed, recoveryWindow })
        return { adminMacaroon }
    }

    PostRestore = async (seed: string[], initMacaroon: string | undefined) => {
        if (this.settings.getSettings().liquiditySettings.useOnlyLiquidityProvider) {
            this.log("USE_ONLY_LIQUIDITY_PROVIDER enabled, skipping LND restore")
            return 'noaction'
        }
        const { lndCert, macaroon } = this.getCreds()
        const m = initMacaroon || macaroon
        const state = this.GetStateClient(lndCert)
        const ln = this.GetLightningClient(lndCert, m)
        const encryptedSeed = this.EncryptWalletSeed(seed)
        this.nodePub = await this.saveSeed(state, ln, encryptedSeed.encryptedData)
        this.subscribeToBackups(ln, state, this.nodePub)
    }

    Unlock = async (): Promise<'created' | 'unlocked' | 'noaction'> => {
        // Skip LND unlock if using only liquidity provider
        if (this.settings.getSettings().liquiditySettings.useOnlyLiquidityProvider) {
            this.log("USE_ONLY_LIQUIDITY_PROVIDER enabled, skipping LND unlock")
            return 'noaction'
        }
        const { lndCert } = this.getCreds()
        const state = this.GetStateClient(lndCert)
        const walletState = await this.WaitWalletState(state, WALLET_STATE_WAIT_SECONDS)
        if (walletState === WalletState.NON_EXISTING) {
            const { ln, seed, candidatePubs } = await this.initFlow(lndCert, state)
            this.nodePub = await this.confirmNewWalletPub(state, ln, candidatePubs, seed.encryptedSeed)
            this.subscribeToBackups(ln, state, this.nodePub)
            return 'created'
        }
        const { ln, pub, action } = await this.unlockFlow(lndCert, state, walletState)
        this.subscribeToBackups(ln, state, pub)
        return action
    }

    private unlockFlow = async (lndCert: Buffer, state: StateClient, walletState: WalletState): Promise<{ ln: LightningClient, pub: string, action: 'unlocked' | 'noaction' }> => {
        const action = walletState === WalletState.LOCKED ? 'unlocked' : 'noaction'
        if (walletState === WalletState.LOCKED) {
            this.log("wallet is locked, unlocking...")
            const walletPassword = this.GetWalletPassword()
            await this.GetUnlockerClient(lndCert).unlockWallet({ walletPassword, recoveryWindow: 0, statelessInit: false, channelBackups: undefined }, DeadLineMetadata())
        }
        await this.WaitWalletState(state, null, WalletState.SERVER_ACTIVE)
        const { macaroon } = this.getCreds()
        if (macaroon === "") {
            throw new Error("lnd is running but no macaroon was found, check LND_MACAROON_PATH")
        }
        const ln = this.GetLightningClient(lndCert, macaroon)
        const pub = await this.waitForNodePub(state, ln)
        this.log(action === 'unlocked' ? "unlocked wallet with pub:" : "the wallet is already unlocked with pub:", pub)
        this.nodePub = pub
        return { ln, pub, action }
    }


    private initFlow = async (lndCert: Buffer, state: StateClient, restore?: { seed: string[], recoveryWindow: number }) => {
        this.log("creating wallet...")
        const stateResult = await this.WaitWalletState(state, WALLET_STATE_WAIT_SECONDS)
        if (stateResult !== WalletState.NON_EXISTING) {
            throw new Error("lnd already has a wallet (state: " + WalletState[stateResult] + "), cannot create one")
        }
        const unlocker = this.GetUnlockerClient(lndCert)
        const seed = await this.getSeed(unlocker, restore)
        const recoveryWindow = restore ? restore.recoveryWindow : 0
        if (recoveryWindow) {
            this.log("recovering addresses with window: " + recoveryWindow)
        }
        const candidatePubs = seed.entropy ? await this.saveSeedUnderCandidatePubs(seed.entropy, seed.encryptedSeed) : []
        const { adminMacaroon } = await this.initWallet(unlocker, seed, recoveryWindow)
        const ln = this.GetLightningClient(lndCert, adminMacaroon)
        return { adminMacaroon, ln, seed, candidatePubs }
    }

    private saveSeedUnderCandidatePubs = async (entropy: Buffer, encryptedSeed: EncryptedData) => {
        const candidatePubs = candidateNodePubkeys(entropy)
        for (const pub of candidatePubs) {
            await this.storage.liquidityStorage.SaveNodeSeed(pub, JSON.stringify(encryptedSeed))
        }
        this.log("seed saved under candidate node keys:", candidatePubs.join(", "))
        return candidatePubs
    }

    private getSeed = async (unlocker: WalletUnlockerClient, restore?: { seed: string[] }): Promise<Seed> => {
        if (restore) {
            if (!restore.seed || restore.seed.length === 0) {
                throw new Error("no seed provided to restore")
            }
            const { encryptedData } = this.EncryptWalletSeed(restore.seed)
            return { plaintextSeed: restore.seed, encryptedSeed: encryptedData }
        }
        return this.genSeed(unlocker)
    }

    private genSeed = async (unlocker: WalletUnlockerClient): Promise<Seed> => {
        const entropy = crypto.randomBytes(16)
        const seedRes = await unlocker.genSeed({
            aezeedPassphrase: Buffer.alloc(0),
            seedEntropy: entropy
        }, DeadLineMetadata())
        this.log("seed created")
        const { encryptedData } = this.EncryptWalletSeed(seedRes.response.cipherSeedMnemonic)
        return { plaintextSeed: seedRes.response.cipherSeedMnemonic, encryptedSeed: encryptedData, entropy }
    }

    private initWallet = async (unlocker: WalletUnlockerClient, seed: Seed, recoveryWindow: number = 0) => {
        const walletPw = this.GetWalletPassword()
        const req = InitWalletReq(walletPw, seed.plaintextSeed, recoveryWindow)
        const initRes = await unlocker.initWallet(req, DeadLineMetadata(60 * 1000))
        const adminMacaroon = Buffer.from(initRes.response.adminMacaroon).toString('hex')

        return { adminMacaroon }
    }

    private saveSeed = async (state: StateClient, ln: LightningClient, encryptedSeed: EncryptedData) => {
        const pub = await this.waitForNodePub(state, ln)
        await this.storage.liquidityStorage.SaveNodeSeed(pub, JSON.stringify(encryptedSeed))
        return pub
    }

    private confirmNewWalletPub = async (state: StateClient, ln: LightningClient, candidatePubs: string[], encryptedSeed: EncryptedData) => {
        const pub = await this.waitForNodePub(state, ln)
        if (!candidatePubs.includes(pub)) {
            this.log(ERROR, "node key derived from seed entropy does not match lnd, saving seed under lnd's key", pub)
            await this.storage.liquidityStorage.SaveNodeSeed(pub, JSON.stringify(encryptedSeed))
        }
        for (const candidate of candidatePubs.filter(c => c !== pub)) {
            await this.storage.liquidityStorage.RemoveNodeSeed(candidate)
        }
        this.log("created wallet with pub:", pub)
        return pub
    }

    private waitForNodePub = async (state: StateClient, ln: LightningClient) => {
        await this.waitForServerActive(state, ln)
        await this.WaitRecovery(ln)
        let info;
        for (let i = 0; i < 10; i++) {
            info = await this.GetLndInfo(ln);
            if (info.ok) break;
            this.log("LND not ready, retrying in 5 seconds...");
            await new Promise(res => setTimeout(res, 5000));
        }

        if (!info || !info.ok) {
            throw new Error("failed to init lnd wallet " + (info ? info.failure : "unknown error"))
        }
        return info.pub
    }

    private waitForServerActive = async (state: StateClient, ln: LightningClient) => {
        const timer = setInterval(() => { void this.logSyncProgress(ln) }, SYNC_PROGRESS_SECONDS * 1000)
        try {
            await this.WaitWalletState(state, null, WalletState.SERVER_ACTIVE)
        } finally {
            clearInterval(timer)
        }
    }

    // The installer parses this line; lnd reports no target height, so the tip is estimated from the header's age.
    private logSyncProgress = async (ln: LightningClient) => {
        try {
            const { blockHeight, bestHeaderTimestamp } = (await ln.getInfo({}, DeadLineMetadata())).response
            const blocksBehind = Math.max(0, Math.floor((Date.now() / 1000 - Number(bestHeaderTimestamp)) / SECONDS_PER_BLOCK))
            const target = blockHeight + blocksBehind
            if (target === 0) return
            const percent = Math.min(99, Math.floor(blockHeight * 100 / target))
            this.log(`LND header sync ${percent}% (height=${blockHeight}/~${target})`)
        } catch { }
    }

    GetSeed = async (): Promise<Types.LndSeed> => {
        if (!this.nodePub) {
            throw new Error("node pub not found")
        }
        const encrypted = await this.storage.liquidityStorage.GetNoodeSeed(this.nodePub)
        if (!encrypted) {
            throw new Error("seed not found")
        }
        const decrypted = this.DecryptWalletSeed(JSON.parse(encrypted))
        return { seed: decrypted }
    }

    GetSeedIfAvailable = async (): Promise<string[]> => {
        try {
            const seed = await this.GetSeed()
            return seed.seed
        } catch (err: any) {
            this.log("failed to get seed", err.message)
            return []
        }
    }

    GetLndInfo = async (ln: LightningClient): Promise<{ ok: false, failure: 'locked' | 'unknown' } | { ok: true, pub: string }> => {
        while (true) {
            try {
                const info = await ln.getInfo({}, DeadLineMetadata())
                return { ok: true, pub: info.response.identityPubkey }
            } catch (err: any) {
                if ((err.message as string).includes('wallet locked, unlock it to enable full RPC access')) {
                    this.log("wallet is locked")
                    return { ok: false, failure: 'locked' }
                } else if ((err.message as string).includes('the RPC server is in the process of starting up, but not yet ready to accept calls')) {
                    this.log("lnd is not ready yet, waiting...")
                    await new Promise((res) => setTimeout(res, 1000))
                } else {
                    this.log("failed to get lnd info", err.message)
                    return { ok: false, failure: 'unknown' }
                }
            }
        }
    }

    EncryptWalletSeed = (seed: string[]) => {
        return this.encrypt(seed.join('+'), true)
    }

    DecryptWalletSeed = (data: { iv: string, encrypted: string }) => {
        return this.decrypt(data).split('+')
    }
    EncryptBackup = (backup: Buffer) => {
        return this.encrypt(backup.toString('hex'))
    }

    DecryptBackup = (data: { iv: string, encrypted: string }) => {
        return Buffer.from(this.decrypt(data), 'hex')
    }

    encrypt = (text: string, must = false) => {
        const sec = this.GetWalletSecret(must)
        if (!sec) {
            throw new Error("wallet secret not found to encrypt")
        }
        const secret = Buffer.from(sec, 'hex')
        const iv = crypto.randomBytes(16)
        const cipher = crypto.createCipheriv('aes-256-cbc', secret, iv)
        const rawData = Buffer.from(text, 'utf-8')
        const cyData = cipher.update(rawData)
        const encrypted = Buffer.concat([cyData, cipher.final()])
        const encryptedData = { iv: iv.toString('hex'), encrypted: encrypted.toString('hex') }
        return { encryptedData }
    }

    decrypt = (data: { iv: string, encrypted: string }) => {
        const sec = this.GetWalletSecret(false)
        if (!sec) {
            throw new Error("wallet secret not found to decrypt")
        }
        const secret = Buffer.from(sec, 'hex')
        const iv = Buffer.from(data.iv, 'hex')
        const encrypted = Buffer.from(data.encrypted, 'hex')
        const decipher = crypto.createDecipheriv('aes-256-cbc', secret, iv)
        const decrypted = decipher.update(encrypted)
        const raw = Buffer.concat([decrypted, decipher.final()])
        return raw.toString('utf-8')
    }

    GetWalletSecret = (create: boolean) => {
        const path = this.settings.getStorageSettings().walletSecretPath
        let secret = ""
        try {
            secret = fs.readFileSync(path, 'utf-8')
        } catch {
            this.log("the wallet secret file was not found")
        }
        if (secret === "" && create) {
            this.log("creating wallet secret file")
            secret = crypto.randomBytes(32).toString('hex')
            fs.writeFileSync(path, secret)
        }
        return secret
    }

    GetWalletPassword = () => {
        const path = this.settings.getStorageSettings().walletPasswordPath
        let password: Buffer | null = null
        try {
            password = fs.readFileSync(path)
        } catch {
        }
        if (!password || password.length === 0) {
            this.log("no wallet password configured, using wallet secret")
            const secret = this.GetWalletSecret(false)
            if (secret === "") {
                throw new Error("no usable password found")
            }
            password = Buffer.from(secret, 'hex')
        }
        return password
    }

    subscribeToBackups = (ln: LightningClient, state: StateClient, pub: string) => {
        if (this.subbedToBackups) {
            return
        }
        this.subbedToBackups = true
        void this.keepBackupsSubscribed(ln, state, pub)
    }

    private keepBackupsSubscribed = async (ln: LightningClient, state: StateClient, pub: string) => {
        while (!this.abortController.signal.aborted) {
            try {
                await this.WaitWalletState(state, null, WalletState.SERVER_ACTIVE)
                await this.streamChannelBackups(ln, pub)
            } catch (err: any) {
                this.log("channel backup subscription failed", err.message || err)
            }
            if (this.abortController.signal.aborted) {
                return
            }
            this.log(`channel backup subscription ended, retrying in ${BACKUP_RESUBSCRIBE_SECONDS} seconds`)
            await new Promise(res => setTimeout(res, BACKUP_RESUBSCRIBE_SECONDS * 1000).unref())
        }
    }

    private streamChannelBackups = (ln: LightningClient, pub: string): Promise<void> => {
        this.log("subscribing to channel backups for: ", pub)
        const stream = ln.subscribeChannelBackups({}, { abort: this.abortController.signal })
        stream.responses.onMessage(msg => this.saveChannelBackup(pub, msg))
        return new Promise(resolve => {
            stream.responses.onError(err => {
                this.log("channel backup stream error", err.message)
                resolve()
            })
            stream.responses.onComplete(() => resolve())
        })
    }

    private saveChannelBackup = async (pub: string, msg: ChanBackupSnapshot) => {
        if (!msg.multiChanBackup) {
            return
        }
        this.log("received backup, saving")
        try {
            const rawBackup = Buffer.from(msg.multiChanBackup.multiChanBackup)
            const { encryptedData } = this.EncryptBackup(rawBackup)
            await this.storage.liquidityStorage.SaveNodeBackup(pub, JSON.stringify(encryptedData))
            await this.publishScbToNostr(rawBackup)
            this.log("new channel backup saved correctly")
        } catch (err: any) {
            this.log("new channel backup was not saved", err.message || err)
        }
    }

    GetAppWithNostrKeys = async (): Promise<AppWithKeys> => {
        const apps = await this.storage.applicationStorage.GetApplications()
        const local = selectDefaultApp(apps, this.settings.getSettings().serviceSettings.defaultAppName)
        if (!local || !local.nostr_private_key || !local.nostr_public_key) {
            throw new Error("local app nostr keys unavailable")
        }
        return { ...local, nostr_private_key: local.nostr_private_key!, nostr_public_key: local.nostr_public_key! }
    }

    private publishScbToNostr = async (scb: Buffer) => {
        if (!this.settings.getSettings().serviceSettings.pushBackupsToNostr) {
            return
        }
        const local = await this.GetAppWithNostrKeys()

        const ck = nip44.getConversationKey(Buffer.from(local.nostr_private_key, 'hex'), local.nostr_public_key)
        const content = nip44.encrypt(scb.toString('base64'), ck)
        const event: UnsignedEvent = {
            content,
            created_at: Math.floor(Date.now() / 1000),
            kind: SCB_BACKUP_KIND,
            pubkey: local.nostr_public_key,
            tags: [['d', SCB_BACKUP_D_TAG]],
        }
        this.nostrSender.Send({ type: 'app', appId: local.app_id }, { type: 'event', event })
    }

    DecryptScbEvent = async (encryptedScb: string, local: AppKeys) => {
        const ck = nip44.getConversationKey(Buffer.from(local.nostr_private_key, 'hex'), local.nostr_public_key)
        const plaintext = nip44.decrypt(encryptedScb, ck).trim()
        const scb = Buffer.from(plaintext, 'base64')
        return scb
    }

    ApplyScb = async (scb: Buffer) => {
        const { lndCert, macaroon } = this.getCreds()
        const ln = this.GetLightningClient(lndCert, macaroon)
        await ln.verifyChanBackup({
            multiChanBackup: { chanPoints: [], multiChanBackup: scb }
        }, DeadLineMetadata())

        await ln.restoreChannelBackups({
            backup: { oneofKind: 'multiChanBackup', multiChanBackup: scb }
        }, DeadLineMetadata())
        await this.WaitRecovery(ln)
        return ln
    }

    GetWalletInfo = async () => {
        const { lndCert, macaroon } = this.getCreds()
        const ln = this.GetLightningClient(lndCert, macaroon)
        const wBalance = await ln.walletBalance({ account: "", minConfs: 0 }, DeadLineMetadata())
        const cBalance = await ln.channelBalance({}, DeadLineMetadata())
        const channels = await ln.listChannels({ activeOnly: false, inactiveOnly: false, privateOnly: false, publicOnly: false, peer: Buffer.alloc(0), peerAliasLookup: false }, DeadLineMetadata())
        const pendingChannels = await ln.pendingChannels({ includeRawTx: false }, DeadLineMetadata())
        const closedChannels = await ln.closedChannels({ abandoned: true, cooperative: true, localForce: true, remoteForce: true, breach: true, fundingCanceled: true }, DeadLineMetadata())
        return { w: wBalance.response, cb: cBalance.response, channels: channels.response, pendingChannels: pendingChannels.response, closedChannels: closedChannels.response }
    }

    WaitRecovery = async (ln: LightningClient) => {
        while (true) {
            const info = await ln.getRecoveryInfo({}, DeadLineMetadata())
            const res = info.response
            if (!res.recoveryMode) {
                this.log("lnd is not in recovery mode")
                return
            }
            if (res.recoveryFinished) {
                this.log("recovery finished")
                return
            }
            this.log("recovery progress: " + res.progress)
            await new Promise(resolve => setTimeout(resolve, 1000))
        }
    }

    GetStateClient = (cert: Buffer): StateClient => {
        const host = this.settings.getSettings().lndNodeSettings.lndAddr
        const channelCredentials = credentials.createSsl(cert)
        const transport = new GrpcTransport({ host, channelCredentials })
        const client = new StateClient(transport)
        return client
    }

    WaitWalletState = (client: StateClient, timeout: number | null, expect: WalletState | null = null): Promise<WalletState> => {
        const abortController = new AbortController()
        this.log(timeout === null ? "Waiting for LND to be ready" : "Waiting for LND to be ready for up to " + timeout + " seconds")
        return new Promise((resolve, reject) => {
            let ended = false
            let timeoutId: NodeJS.Timeout | null = null
            const done = (msgState: WalletState) => {
                if (ended) return
                ended = true
                if (timeoutId) clearTimeout(timeoutId)
                resolve(msgState)
                abortController.abort()
            }
            const fail = (err: any) => {
                if (ended) return
                ended = true
                if (timeoutId) clearTimeout(timeoutId)
                reject(err)
                abortController.abort()
            }

            if (timeout !== null) {
                timeoutId = setTimeout(() => fail(new Error("LND state stream timed out")), timeout * 1000)
            }
            const stream = client.subscribeState({}, { abort: abortController.signal })
            stream.responses.onMessage(async (msg) => {
                this.log("Current LND state: ", msg.state)
                if (expect === null) {
                    if (msg.state !== WalletState.WAITING_TO_START) {
                        done(msg.state)
                    }
                } else if (msg.state === expect) {
                    done(msg.state)
                }

            })
            stream.responses.onError(err => {
                fail(err)
            })
            stream.responses.onComplete(() => {
                fail(new Error("LND state stream closed"))
            })
        })
    }

    GetUnlockerClient = (cert: Buffer) => {
        const host = this.settings.getSettings().lndNodeSettings.lndAddr
        const channelCredentials = credentials.createSsl(cert)
        const transport = new GrpcTransport({ host, channelCredentials })
        const client = new WalletUnlockerClient(transport)
        return client
    }
    GetLightningClient = (cert: Buffer, macaroon: string) => {
        const host = this.settings.getSettings().lndNodeSettings.lndAddr
        const sslCreds = credentials.createSsl(cert)
        const macaroonCreds = credentials.createFromMetadataGenerator(
            function (args: any, callback: any) {
                let metadata = new Metadata();
                metadata.add('macaroon', macaroon);
                callback(null, metadata);
            },
        );
        const channelCredentials = credentials.combineChannelCredentials(
            sslCreds,
            macaroonCreds,
        );
        const transport = new GrpcTransport({ host, channelCredentials })
        const client = new LightningClient(transport)
        return client
    }
}
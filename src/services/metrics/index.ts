    async StampActiveChannels() {
        const { channels } = await this.lnd.ListChannels()
        await this.storage.metricsStorage.MarkChannelsSeen(
            channels.filter(c => c.active).map(c => c.chanId),
            60,
        )
        this.rememberChannelAliases(channels)
        void this.RefreshChannelAliases()
    }

    rememberChannelAliases(channels: Channel[]) {
        const changed = mergeAliasMaps(this.channelAliases, aliasByRemotePubkey(channels))
        if (changed) this.lndMetricsCache.ClearAll()
    }

    async RefreshChannelAliases() {
        if (this.channelAliasRefresh) return this.channelAliasRefresh
        if (Date.now() < this.nextChannelAliasRefreshAt) return

        this.nextChannelAliasRefreshAt = Date.now() + CHANNEL_ALIAS_RETRY_TTL_MS
        const refresh = this.loadGraphAliases().finally(() => {
            this.channelAliasRefresh = null
        })
        this.channelAliasRefresh = refresh
        return refresh
    }

    private async loadGraphAliases() {
        try {
            const { channels } = await this.lnd.ListChannels(true)
            this.rememberChannelAliases(channels)
            this.nextChannelAliasRefreshAt = Date.now() + CHANNEL_ALIAS_CACHE_TTL_MS
        } catch (err: any) {
            this.logger("failed to refresh channel aliases", err.message || err)
        }
    }

    async GetProvidersDisruption(): Promise<Types.ProvidersDisruption> {
        const providers = await this.storage.liquidityStorage.GetTrackedProviders()
        const disruptions = providers.filter(p => p.latest_distruption_at_unix > 0 && p.provider_type !== 'lnd').map(d => ({
            provider_pubkey: d.provider_pubkey,
            provider_type: d.provider_type,
            since_unix: d.latest_distruption_at_unix
        }))
        if (this.lnd.outgoingOpsLocked) {
            disruptions.push({
                provider_pubkey: "",
                provider_type: 'lnd',
                since_unix: Math.floor(Date.now() / 1000)
            })
        }
        return {
            disruptions: disruptions
        }
    }

    async ChannelEventCb(event: ChannelEventUpdate, channels: Channel[]) {
        this.rememberChannelAliases(channels)
        if (event.channel.oneofKind === 'inactiveChannel') {
            const channel = this.getRelevantChannel(event.channel.inactiveChannel, channels)
            if (!channel) {
                return
            }
            await this.storage.metricsStorage.MarkChannelsSeen([channel.chanId])
            return
        } else if (event.channel.oneofKind === 'activeChannel') {
            const channel = this.getRelevantChannel(event.channel.activeChannel, channels)
            if (!channel) {
                return
            }
            await this.storage.metricsStorage.MarkChannelsSeen([channel.chanId])
            return
        }
    }

    getRelevantChannel(point: ChannelPoint, channels: Channel[]) {
        const key = channelPointKey(point)
        if (!key) return undefined
        return channels.find(c => c.channelPoint.toLowerCase() === key)
    }



    async HtlcCb(htlc: HtlcEvent) {
        await this.htlcTracker.onHtlcEvent(htlc)
    }

    async NewBlockCb(height: number, balanceInfo: BalanceInfo) {
        const providers = await this.storage.liquidityStorage.GetTrackedProviders()
        const channels = await this.lnd.GetChannelBalance()
        let providerTotal = 0
        providers.forEach(p => {
            if (p.provider_type === 'lnPub') {
                providerTotal += p.latest_balance
            }
        })
        const balanceEvent: Partial<BalanceEvent> = {
            block_height: height,
            confirmed_chain_balance: balanceInfo.confirmedBalance,
            unconfirmed_chain_balance: balanceInfo.unconfirmedBalance,
            total_chain_balance: balanceInfo.totalBalance,
            channels_balance: Number(channels.localBalance?.sat) || 0,
            external_balance: providerTotal
        }
        const channelsEvents: Partial<ChannelBalanceEvent>[] = balanceInfo.channelsBalance.map(c => ({
            channel_id: c.channelId,
            local_balance_sats: c.localBalanceSats,
            remote_balance_sats: c.remoteBalanceSats,
        }))
        await this.storage.metricsStorage.SaveBalanceEvents(balanceEvent, channelsEvents)
        await this.FetchLatestForwardingEvents()
        try {
            await this.storage.metricsStorage.MarkChannelsSeen(
                balanceInfo.channelsBalance.filter(c => c.active).map(c => c.channelId),
                60,
            )
        } catch (err: any) {
            this.logger("failed to stamp channel last seen", err.message || err)
        }
    }

    async FetchLatestForwardingEvents() {
        const latestIndex = await this.storage.metricsStorage.GetLatestForwardingIndexOffset()
        const res = await this.lnd.GetForwardingHistory(latestIndex)
        const forwards = res.forwardingEvents.map(e => ({ fee: Number(e.fee), chanIdIn: e.chanIdIn, chanIdOut: e.chanIdOut, timestampNs: e.timestampNs.toString(), offset: res.lastOffsetIndex }))
        await Promise.all(forwards.map(async f => {
            await this.storage.metricsStorage.IncrementChannelRouting(f.chanIdIn, { forward_fee_as_input: f.fee, latest_index_offset: f.offset, events_as_input: 1 })
            await this.storage.metricsStorage.IncrementChannelRouting(f.chanIdOut, { forward_fee_as_output: f.fee, latest_index_offset: f.offset, events_as_output: 1 })
        }))
    }


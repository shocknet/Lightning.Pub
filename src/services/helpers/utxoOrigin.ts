import { Transaction as BitcoinTransaction } from 'bitcoinjs-lib'
import { UtxoOrigin } from '../../../proto/autogenerated/ts/types.js'
import type { Transaction, OutputDetail } from '../../../proto/lnd/lightning.js'

export type OriginTransaction = Pick<Transaction, 'txHash' | 'rawTxHex' | 'previousOutpoints' | 'outputDetails'>
export type UtxoClassification = { origin: UtxoOrigin; is_change: boolean }

/** Rebuild from evidence rather than persisting labels that could survive a reorg.
 * All outputs participate in the graph: force-close/HTLC intermediates need not
 * be wallet-owned. Only wallet inputs and known channel outputs carry provenance.
 */
export function classifyUtxos(
    transactions: OriginTransaction[],
    userAddresses: Set<string>,
    userOutpoints: Set<string>,
    channelTxids: Set<string>,
    changeAddresses: Set<string>,
): Map<string, UtxoClassification> {
    const txs = new Map(transactions.map(tx => [tx.txHash, tx]))
    const outputs = new Map<string, OutputDetail>(transactions.flatMap(tx => tx.outputDetails.map(output =>
        [`${tx.txHash}:${output.outputIndex}`, output] as const)))
    const inputs = new Map(transactions.map(tx => [tx.txHash, transactionInputs(tx)]))
    const remaining = new Map<string, number>()
    const children = new Map<string, string[]>()
    const ready: string[] = []
    for (const [hash, prev] of inputs) {
        const parents = new Set(prev.map(p => txid(p.outpoint)).filter(hash => txs.has(hash)))
        remaining.set(hash, parents.size)
        if (parents.size === 0) ready.push(hash)
        for (const parent of parents) {
            const list = children.get(parent) || []
            list.push(hash)
            children.set(parent, list)
        }
    }
    const result = new Map<string, UtxoClassification>()
    for (let i = 0; i < ready.length; i++) {
        const hash = ready[i]
        const tx = txs.get(hash)!
        const origins: UtxoOrigin[] = []
        for (const input of inputs.get(hash)!) {
            const parentOutput = outputs.get(input.outpoint)
            const parentOrigin = result.get(input.outpoint)?.origin
            // A channel commitment's non-wallet outputs can lead to HTLC sweeps.
            if (input.isOurOutput || parentOutput?.isOurAddress || userOutpoints.has(input.outpoint)
                || channelTxids.has(txid(input.outpoint)) || parentOrigin === UtxoOrigin.CHANNEL || parentOrigin === UtxoOrigin.MIXED) {
                origins.push(parentOrigin
                    ?? (channelTxids.has(txid(input.outpoint)) ? UtxoOrigin.CHANNEL
                        : userOutpoints.has(input.outpoint) ? UtxoOrigin.USER_DEPOSIT : UtxoOrigin.UNKNOWN))
            }
        }
        const inherited = channelTxids.has(hash) ? UtxoOrigin.CHANNEL : mergeOrigins(origins)
        for (const output of tx.outputDetails) {
            const point = `${hash}:${output.outputIndex}`
            const deposit = userOutpoints.has(point) || userAddresses.has(output.address)
            result.set(point, {
                origin: deposit ? UtxoOrigin.USER_DEPOSIT : inherited,
                is_change: changeAddresses.has(output.address),
            })
        }
        for (const child of children.get(hash) || []) {
            const count = remaining.get(child)! - 1
            remaining.set(child, count)
            if (count === 0) ready.push(child)
        }
    }
    return result
}

function transactionInputs(tx: OriginTransaction) {
    if (tx.previousOutpoints.length) return tx.previousOutpoints
    // Older LND versions may omit previous_outpoints. Decode raw history instead.
    try {
        return BitcoinTransaction.fromHex(tx.rawTxHex).ins.map(input => ({
            outpoint: `${Buffer.from(input.hash).reverse().toString('hex')}:${input.index}`,
            // Without LND's ownership flags, missing parents must stay unknown.
            isOurOutput: true,
        }))
    } catch {
        return []
    }
}

function txid(point: string) { return point.split(':')[0] }

function mergeOrigins(origins: UtxoOrigin[]): UtxoOrigin {
    const user = origins.includes(UtxoOrigin.USER_DEPOSIT)
    const channel = origins.includes(UtxoOrigin.CHANNEL)
    if (origins.includes(UtxoOrigin.MIXED) || (user && channel)) return UtxoOrigin.MIXED
    if (origins.length === 0 || origins.includes(UtxoOrigin.UNKNOWN)) return UtxoOrigin.UNKNOWN
    return user ? UtxoOrigin.USER_DEPOSIT : UtxoOrigin.CHANNEL
}

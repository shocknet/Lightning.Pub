import { nip19 } from "@shocknet/clink-sdk"
import { UnsignedEvent } from "nostr-tools"
import { Application } from "../storage/entity/Application.js"
import * as Types from "../../../proto/autogenerated/ts/types.js"
import {
    CLINK_BEACON_D_TAG, CLINK_BEACON_KIND, CLINK_SUPPORTED_KINDS, CLINK_VERSION, LEGACY_BEACON_D_TAG,
} from "./clinkConstants.js"
import { isHttpsAvatarUrl } from "./httpsAvatarUrl.js"

export type ClinkBeaconContent = {
    name?: string
    avatarUrl?: string
    website?: string
    description?: string
    relays?: string[]
    fees?: { serviceFeeFloor: number, serviceFeeBps: number }
    enroll_difficulty?: number
    supported_kinds?: number[]
}

export const operatorPubkeyHex = (npubOrHex: string): string | undefined => {
    if (!npubOrHex) {
        return undefined
    }
    if (/^[0-9a-f]{64}$/i.test(npubOrHex)) {
        return npubOrHex.toLowerCase()
    }
    try {
        const decoded = nip19.decode(npubOrHex)
        if (decoded.type === "npub" && typeof decoded.data === "string") {
            return decoded.data.toLowerCase()
        }
    } catch {
        return undefined
    }
    return undefined
}

export const buildClinkBeaconContent = (args: {
    app: Application
    relays: string[]
    fees: Types.CumulativeFees
    enrollPowBits: number
    website?: string
    description?: string
}): ClinkBeaconContent => {
    const content: ClinkBeaconContent = {
        name: args.app.name,
        relays: args.relays,
        fees: {
            serviceFeeFloor: args.fees.serviceFeeFloor,
            serviceFeeBps: args.fees.serviceFeeBps,
        },
        supported_kinds: [...CLINK_SUPPORTED_KINDS],
    }
    const website = args.website?.trim()
    const description = args.description?.trim()
    const avatar = args.app.avatar_url?.trim()
    if (avatar && isHttpsAvatarUrl(avatar)) {
        content.avatarUrl = avatar
    }
    if (website) {
        content.website = website
    }
    if (description) {
        content.description = description
    }
    if (args.enrollPowBits > 0) {
        content.enroll_difficulty = args.enrollPowBits
    }
    return content
}

export const buildServiceBeaconEvent = (
    pubkey: string,
    beacon: Types.BeaconData,
    clink: ClinkBeaconContent,
    operatorHex?: string,
): UnsignedEvent => {
    const tags: string[][] = [
        ["d", LEGACY_BEACON_D_TAG],
        ["d", CLINK_BEACON_D_TAG],
        ["clink_version", CLINK_VERSION],
    ]
    if (operatorHex) {
        tags.push(["operator", operatorHex])
    }
    return {
        content: JSON.stringify({
            ...beacon,
            relays: clink.relays,
            website: clink.website,
            description: clink.description,
            enroll_difficulty: clink.enroll_difficulty,
            supported_kinds: clink.supported_kinds,
        }),
        created_at: Math.floor(Date.now() / 1000),
        kind: CLINK_BEACON_KIND,
        pubkey,
        tags,
    }
}
